def power_up():
    freq_data = db_block(MAIN_ASM, "PowerUpGrabFreqData")[:27]
    length, = asm_value(r"PlayPowerUpGrab:\s*\n\s*lda #\$([0-9a-fA-F]+)")
    ctrl, = asm_value(r"ContinuePowerUpGrab:(?:.|\n)*?ldx #\$([0-9a-fA-F]+)")
    events, counter, frame = [], length, 0           # replay ContinuePowerUpGrab
    while True:
        if counter % 2 == 0:
            t = timer_from_offset(freq_data[counter // 2 - 1])
            if t is not None:
                events.append((frame, t))
        counter -= 1
        frame += 1
        if counter == 0:
            break
    durations = [b[0] - a[0] for a, b in zip(events, events[1:])] + [frame - events[-1][0]]
    label = "SoundD2_MarioPowerUp"
    lines = header("D2", label, psg_attenuation(ctrl & 15),
                   f"; SMB1 Sfx_PowerUpGrab (square 2): {len(events)} tones, {frame} frames, exact pitches.")
    detune = None
    for (f, t), dur in zip(events, durations):
        note, d, n, desc = psg_note(t)
        if d != detune:
            lines.append(f"\tsmpsDetune          ${d & 0xFF:02X}\t; {d:+d}")
            detune = d
        lines.append(f"\tdc.b\t{note}, ${dur:02X}\t; {desc}")
    lines.append("\tsmpsStop")
    write("D2 - Mario Power Up.asm", lines)


