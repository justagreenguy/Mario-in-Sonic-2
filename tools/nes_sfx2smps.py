def power_down():
    length, = asm_value(r"PlayPipeDownInj:\s*\n\s*lda #\$([0-9a-fA-F]+)")
    sweep, ctrl, offset = asm_value(r"ContinuePipeDownInj:(?:.|\n)*?ldy #\$([0-9a-fA-F]+)\s*;.*\n"
                                    r"\s*ldx #\$([0-9a-fA-F]+)\s*\n\s*lda #\$([0-9a-fA-F]+)")
    t0 = timer_from_offset(offset)
    enabled, period, negate, shift = sweep >> 7, (sweep >> 4) & 7, (sweep >> 3) & 1, sweep & 7
    if not (enabled and period == 1 and not negate and shift):
        sys.exit(f"sweep ${sweep:02X}: only an enabled, period-1, upward sweep is modelled")

    # One sweep from a register write: the timer each frame until it's muted.
    tones, t = [], t0
    while t >= 8 and t + (t >> shift) <= 0x7FF:
        tones.append(t)
        t += t >> shift

    # ContinuePipeDownInj: which frames write the registers.
    writes, counter, frame = [], length, 0
    while True:
        c = counter
        if not (c & 1) and not (c & 2) and (c & 8):
            writes.append(frame)
        counter -= 1                                  # DecrementSfx1Length
        frame += 1
        if counter == 0:
            break
    total = frame

    # Segments: from each write to the next one (or the end).
    segs = []
    for i, w in enumerate(writes):
        end = writes[i + 1] if i + 1 < len(writes) else total
        playing = min(end - w, len(tones))
        segs.append((playing, end - w - playing))

    label = "SoundD1_MarioPowerDown"
    lines = header("D1", label, psg_attenuation(ctrl & 15),
                   f"; SMB1 Sfx_PipeDown (square 1, used for injury): hardware sweep simulated;"
                   f" {len(writes)} sweeps, {total} frames.")
    if writes[0]:
        lines.append(f"\tdc.b\tnRst, ${writes[0]:02X}")
    for playing, rest in segs:
        lines.append(f"\tsmpsCall            {label}_Sweep{playing}")
        if rest:
            lines.append(f"\tdc.b\tnRst, ${rest:02X}")
    lines.append("\tsmpsStop")
    # Sweep subroutines, one per segment length; a longer one calls the next
    # shorter one for its first frames (one nesting level: the gosub stack
    # then overlaps only the loop counters, which these sounds don't use).
    if len({p for p, _ in segs}) > 2:
        sys.exit("more than two sweep lengths: calls would nest deeper than one level")
    prev = 0
    for count in sorted({p for p, _ in segs}):
        lines.append("")
        lines.append(f"; sweep from timer ${t0:03X}, {count} frames (then muted or restarted)")
        lines.append(f"{label}_Sweep{count}:")
        detune = None                                  # unknown on entry
        if prev:
            lines.append(f"\tsmpsCall            {label}_Sweep{prev}")
            detune = psg_note(tones[prev - 1])[1]
        for t in tones[prev:count]:
            note, d, n, desc = psg_note(t)
            if d != detune:
                lines.append(f"\tsmpsDetune          ${d & 0xFF:02X}\t; {d:+d}")
                detune = d
            lines.append(f"\tdc.b\t{note}, $01\t; {desc}")
        lines.append("\tsmpsReturn")
        prev = count
    write("D1 - Mario Power Down.asm", lines)
    print(f"power-down: writes at frames {writes}, sweep {[hex(t) for t in tones]}, {total} frames")


# ---------------------------------------------------------------------------
# General square-channel simulation (Phase 6 sounds).
# Frame-level model of the NES pulse channel: register writes at given frames;
# the sweep unit is clocked twice per frame (half-frame clock). On a sweep
# write the divider reloads with P, so the first step comes P+1 half-frames
# later (one per frame for P=1, the model the power-down uses too). Square 1
# negates with one's complement: target = t - (t >> S) - 1. The channel is
# muted while t < 8 or, without negate, the target exceeds $7FF.
# ---------------------------------------------------------------------------
def simulate_square(length, writes, square1=True):
    """writes: {frame: dict(sweep=, timer=)}; returns the audible timer per frame (None = muted)."""
    timer, sweep, divider, reload = None, 0, 0, False
    out = []
    for f in range(length):
        w = writes.get(f, {})
        if "timer" in w:
            timer = w["timer"]
        if "timer_lo" in w:                                # $4002 only: high bits kept
            timer = (timer & 0x700) | w["timer_lo"]
        if "sweep" in w:
            sweep, reload = w["sweep"], True
        enabled, period, negate, shift = sweep >> 7, (sweep >> 4) & 7, (sweep >> 3) & 1, sweep & 7

        def target(t):
            if negate:
                return t - (t >> shift) - (1 if square1 else 0)
            return t + (t >> shift)

        muted = timer is None or timer < 8 or (not negate and target(timer) > 0x7FF)
        out.append(None if muted else timer)
        for _ in range(2):                                 # two half-frame clocks
            if divider == 0 and enabled and shift and timer is not None and not (
                    timer < 8 or (not negate and target(timer) > 0x7FF)):
                timer = target(timer)
            if divider == 0 or reload:
                divider, reload = period, False
            else:
                divider -= 1
    return out


def emit_timeline(label, lines, timeline):
    """Append SMPS notes for a per-frame timer list (runs of equal values merged)."""
    detune = None
    i = 0
    while i < len(timeline):
        j = i
        while j < len(timeline) and timeline[j] == timeline[i]:
            j += 1
        dur, t = j - i, timeline[i]
        if t is None:
            lines.append(f"\tdc.b\tnRst, ${dur:02X}")
        else:
            note, d, n, desc = psg_note(t)
            if d != detune:
                lines.append(f"\tsmpsDetune          ${d & 0xFF:02X}\t; {d:+d}")
                detune = d
            lines.append(f"\tdc.b\t{note}, ${dur:02X}\t; {desc}")
        i = j
    lines.append("\tsmpsStop")


def fireball_and_bump():
    """Sfx_Fireball and Sfx_Bump (square 1): PlayFireballThrow / PlayBump share
    Fthrow's control and timer; ContinueBumpThrow rewrites the sweep register
    when the length counter reaches a given value (only the bump is long enough)."""
    fb_len, fb_sweep = asm_value(r"PlayFireballThrow:\s*\n\s*lda #\$([0-9a-fA-F]+)\s*\n\s*ldy #\$([0-9a-fA-F]+)")
    bump_len, bump_sweep = asm_value(r"PlayBump:\s*\n\s*lda #\$([0-9a-fA-F]+)[^\n]*\n\s*ldy #\$([0-9a-fA-F]+)")
    ctrl, offset = asm_value(r"Fthrow:\s*\n\s*ldx #\$([0-9a-fA-F]+)(?:.|\n)*?lda #\$([0-9a-fA-F]+)")
    at_count, sweep2 = asm_value(r"ContinueBumpThrow:(?:.|\n)*?cmp #\$([0-9a-fA-F]+)(?:.|\n)*?lda #\$([0-9a-fA-F]+)")
    t0 = timer_from_offset(offset)
    for slot, name, file, length, sweep in [
            ("B8", "MarioFireball", "B8 - Mario Fireball.asm", fb_len, fb_sweep),
            ("C7", "MarioBump", "C7 - Mario Bump.asm", bump_len, bump_sweep)]:
        writes = {0: dict(sweep=sweep, timer=t0)}
        # the length counter is `length` on frame 0 and counts down each frame
        if 0 <= length - at_count < length:
            writes[length - at_count] = dict(sweep=sweep2)
        timeline = simulate_square(length, writes)
        label = f"Sound{slot}_{name}"
        lines = header(slot, label, psg_attenuation(ctrl & 15),
                       f"; SMB1 {'Sfx_Fireball' if slot == 'B8' else 'Sfx_Bump'} (square 1): sweep simulated;"
                       f" {length} frames.")
        emit_timeline(label, lines, timeline)
        write(file, lines)
        print(f"{name}: {[None if t is None else hex(t) for t in timeline]}")


def envelope_attenuation(v):
    """NES volume 1-15 -> PSG attenuation (2 dB steps), relative to 15 = full volume."""
    return int(round(-20 * math.log10(v / 15) / 2))


def swim_stomp():
    """Sfx_EnemyStomp, SMB1's swim stroke / stomp sound (square 1). PlaySwimStomp
    writes control, sweep and timer; every frame ContinueSwimStomp then rewrites
    the volume from SwimStompEnvelopeData[length left - 1], and when the length
    left reaches a given value it writes the timer's low byte directly. The
    volume envelope is emitted as smpsPSGAlterVol steps (peak 15 = full volume)."""
    length, sweep, ctrl, offset = asm_value(
        r"PlaySwimStomp:\s*\n\s*lda #\$([0-9a-fA-F]+)[^\n]*\n[^\n]*\n\s*ldy #\$([0-9a-fA-F]+)[^\n]*\n"
        r"\s*ldx #\$([0-9a-fA-F]+)\s*\n\s*lda #\$([0-9a-fA-F]+)")
    at_count, lo = asm_value(r"ContinueSwimStomp:(?:.|\n)*?cpy #\$([0-9a-fA-F]+)(?:.|\n)*?lda #\$([0-9a-fA-F]+)")
    env = db_block(MAIN_ASM, "SwimStompEnvelopeData")
    if not ctrl & 0x10 or any(not e & 0x10 for e in env):
        sys.exit("swim/stomp: only constant-volume envelopes are modelled")
    writes = {0: dict(sweep=sweep, timer=timer_from_offset(offset))}
    writes[length - at_count] = dict(timer_lo=lo)
    timeline = simulate_square(length, writes)
    vols = [env[length - f - 1] & 15 for f in range(length)]   # counter = length - f
    frames = [(t, v) if t is not None and v else (None, 0) for t, v in zip(timeline, vols)]

    label = "SoundA9_MarioSwimStomp"
    first = next(envelope_attenuation(v) for t, v in frames if v)
    lines = header("A9", label, first,
                   f"; SMB1 Sfx_EnemyStomp (square 1, swim stroke/stomp): sweep and volume envelope simulated;"
                   f" {length} frames.")
    detune, att = None, first
    i = 0
    while i < len(frames):
        j = i
        while j < len(frames) and frames[j] == frames[i]:
            j += 1
        (t, v), dur = frames[i], j - i
        if t is None:
            lines.append(f"\tdc.b\tnRst, ${dur:02X}")
        else:
            a = envelope_attenuation(v)
            if a != att:
                lines.append(f"\tsmpsPSGAlterVol     ${(a - att) & 0xFF:02X}\t; NES volume {v}")
                att = a
            note, d, n, desc = psg_note(t)
            if d != detune:
                lines.append(f"\tsmpsDetune          ${d & 0xFF:02X}\t; {d:+d}")
                detune = d
            lines.append(f"\tdc.b\t{note}, ${dur:02X}\t; {desc}")
        i = j
    lines.append("\tsmpsStop")
    write("A9 - Mario Swim Stomp.asm", lines)
    print(f"swim/stomp: {[(None if t is None else hex(t), v) for t, v in frames]}")


# ---------------------------------------------------------------------------
# Full NES APU channel model (jump sounds, death music): register writes, the
# volume envelope, the length counter, the sweep unit and the triangle's
# linear counter. Each frame: the sound engine's writes, then the frame
# sequencer's four quarter-frame clocks (half-frame clocks with the 2nd and
# 4th). A frame's output is sampled after its first quarter-frame clock.
# ---------------------------------------------------------------------------
LENGTH_TABLE = [10, 254, 20, 2, 40, 4, 80, 6, 160, 8, 60, 10, 14, 12, 26, 14,
                12, 16, 24, 18, 48, 20, 96, 22, 192, 24, 72, 26, 16, 28, 32, 30]
MUSIC_ASM = os.path.join(SMB, "audio", "music.asm")


class Pulse:
    def __init__(self, square1):
        self.square1 = square1
        self.ctrl = self.sweep = self.timer = self.length = 0
        self.env_start, self.decay, self.env_div = False, 0, 0
        self.sw_div, self.sw_reload = 0, False

    def write(self, reg, v):
        if reg == 0:
            self.ctrl = v
        elif reg == 1:
            self.sweep, self.sw_reload = v, True
        elif reg == 2:
            self.timer = (self.timer & 0x700) | v
        else:
            self.timer = (self.timer & 0xFF) | (v & 7) << 8
            self.length = LENGTH_TABLE[v >> 3]
            self.env_start = True

    def target(self):
        sh = self.sweep & 7
        if self.sweep & 8:
            return self.timer - (self.timer >> sh) - (1 if self.square1 else 0)
        return self.timer + (self.timer >> sh)

    def sweep_mute(self):
        # the sweep unit mutes the channel whatever its enable bit says
        return self.timer < 8 or (not self.sweep & 8 and self.target() > 0x7FF)

    def output(self):
        if self.length == 0 or self.sweep_mute():
            return None
        v = self.ctrl & 15 if self.ctrl & 0x10 else self.decay
        return (self.timer, v) if v else None

    def quarter(self):
        if self.env_start:
            self.env_start, self.decay, self.env_div = False, 15, self.ctrl & 15
        elif self.env_div == 0:
            self.env_div = self.ctrl & 15
            if self.decay:
                self.decay -= 1
            elif self.ctrl & 0x20:
                self.decay = 15
        else:
            self.env_div -= 1

    def half(self):
        if not self.ctrl & 0x20 and self.length:
            self.length -= 1
        if self.sw_div == 0 and self.sweep & 0x80 and self.sweep & 7 and not self.sweep_mute():
            self.timer = self.target()
        if self.sw_div == 0 or self.sw_reload:
            self.sw_div, self.sw_reload = (self.sweep >> 4) & 7, False
        else:
            self.sw_div -= 1


class Triangle:
    def __init__(self):
        self.ctrl = self.timer = self.length = self.linear = 0
        self.lin_reload = False

    def write(self, reg, v):
        if reg == 0:
            self.ctrl = v
        elif reg == 2:
            self.timer = (self.timer & 0x700) | v
        elif reg == 3:
            self.timer = (self.timer & 0xFF) | (v & 7) << 8
            self.length = LENGTH_TABLE[v >> 3]
            self.lin_reload = True

    def output(self):
        return None if self.length == 0 or self.linear == 0 or self.timer < 2 else (self.timer, 15)

    def quarter(self):
        if self.lin_reload:
            self.linear = self.ctrl & 0x7F
        elif self.linear:
            self.linear -= 1
        if not self.ctrl & 0x80:
            self.lin_reload = False

    def half(self):
        if not self.ctrl & 0x80 and self.length:
            self.length -= 1


def clock_frame(channels):
    """Sample each channel after the first quarter-frame clock, then finish the frame."""
    for ch in channels:
        ch.quarter()
    out = [ch.output() for ch in channels]
    for step in (2, 3, 4):
        for ch in channels:
            ch.quarter()
            if step in (2, 4):
                ch.half()
    return out


def dump_freq(ch, offset):
    """Dump_Freq_Regs: FreqRegLookupTbl[offset+1] -> timer low (0 = no tone, nothing
    written), [offset] | 8 -> timer high + length counter. Returns True for a tone."""
    lo = REGTBL[offset + 1]
    if not lo:
        return False
    ch.write(2, lo)
    ch.write(3, REGTBL[offset] | 8)
    return True


def emit_psg(lines, frames, att_of, note_of, att0, loop_label=None):
    """SMPS PSG notes for per-frame (timer, volume) samples (None = rest). Runs of
    equal samples are merged; volume changes are smpsPSGAlterVol steps from att0.
    With loop_label, the track ends by restoring att0 and jumping there instead of
    stopping (the label must be at the start of `frames`)."""
    detune, att, i = None, att0, 0
    while i < len(frames):
        j = i
        while j < len(frames) and frames[j] == frames[i]:
            j += 1
        dur, s = j - i, frames[i]
        if s is not None:
            a = att_of(s[1])
            if a != att:
                lines.append(f"\tsmpsPSGAlterVol     ${(a - att) & 0xFF:02X}\t; NES volume {s[1]}")
                att = a
            note, d, desc = note_of(s[0])
            if d != detune:
                lines.append(f"\tsmpsDetune          ${d & 0xFF:02X}\t; {d:+d}")
                detune = d
        while dur:
            k = min(dur, 0x7F)
            lines.append(f"\tdc.b\tnRst, ${k:02X}" if s is None else f"\tdc.b\t{note}, ${k:02X}\t; {desc}")
            dur -= k
        i = j
    if loop_label is None:
        lines.append("\tsmpsStop")
        return
    if att != att0:
        lines.append(f"\tsmpsPSGAlterVol     ${(att0 - att) & 0xFF:02X}\t; back to the loop start's volume")
    lines.append(f"\tsmpsJump            {loop_label}")


def pulse_note(t):
    note, d, n, desc = psg_note(t)
    return note, d, desc


def triangle_note(t):
    """The triangle sounds an octave below a pulse with the same timer (32-step
    sequence): PSG divider = 2 * (t + 1)."""
    n = int(round(2 * (t + 1) * PSG_CLOCK * 16 / (32 * NES_CPU)))
    folded = ""
    if n > 0x3FF:
        # below the PSG's lowest pitch (~109 Hz; the victory music's lowest bass
        # notes): this note only is played an octave higher
        n = int(round((t + 1) * PSG_CLOCK * 16 / (32 * NES_CPU)))
        folded = ", an octave up (below the PSG's range)"
    idx = min(range(len(TABLE)), key=lambda i: abs(TABLE[i] - n))
    d = n - TABLE[idx]
    return note_name(idx), d, f"NES triangle timer ${t:03X}: {NES_CPU / (32 * (t + 1)):.1f} Hz{folded}"


# User decision (2026-10-10): the jumps were a little quiet next to S2's sounds.
# Their NES envelope is kept, but every step is this many PSG attenuation steps
# (2 dB each) louder, clamped at full volume.
JUMP_VOLUME_BOOST = 2


def jump_attenuation(v):
    return max(0, envelope_attenuation(v) - JUMP_VOLUME_BOOST)


def jumps():
    """Sfx_BigJump / Sfx_SmallJump (square 1). PlayBigJump / PlaySmallJump load the
    timer offset, JumpRegContents writes control, sweep and timer and sets the
    length; ContinueSndJump rewrites control and sweep (Dump_Squ1_Regs, no timer
    write: the envelope keeps running) when the length left reaches two values.
    DecrementSfx1Length stops the channel ($4015) when it reaches 0."""
    small, = asm_value(r"PlaySmallJump:\s*\n\s*lda #\$([0-9a-fA-F]+)")
    big, = asm_value(r"PlayBigJump:\s*\n\s*lda #\$([0-9a-fA-F]+)")
    ctrl0, sweep0, length = asm_value(r"JumpRegContents:\s*\n\s*ldx #\$([0-9a-fA-F]+)[^\n]*\n\s*ldy #\$([0-9a-fA-F]+)"
                                      r"(?:.|\n)*?lda #\$([0-9a-fA-F]+)")
    at1, ctrl1, sweep1, at2, ctrl2, sweep2 = asm_value(
        r"ContinueSndJump:(?:.|\n)*?cmp #\$([0-9a-fA-F]+)(?:.|\n)*?ldx #\$([0-9a-fA-F]+)[^\n]*\n\s*ldy #\$([0-9a-fA-F]+)"
        r"(?:.|\n)*?cmp #\$([0-9a-fA-F]+)(?:.|\n)*?ldx #\$([0-9a-fA-F]+)(?:.|\n)*?FPS2nd:\s*\n\s*ldy #\$([0-9a-fA-F]+)")
    for slot, name, file, offset, sfx in [("A0", "MarioBigJump", "A0 - Mario Big Jump.asm", big, "Sfx_BigJump"),
                                           ("A4", "MarioSmallJump", "A4 - Mario Small Jump.asm", small, "Sfx_SmallJump")]:
        sq = Pulse(True)
        frames, counter, f = [], length, 0
        while True:
            if f == 0:
                sq.write(1, sweep0); sq.write(0, ctrl0)        # PlaySqu1Sfx: Dump_Squ1_Regs
                dump_freq(sq, offset)
            elif counter == at1:
                sq.write(1, sweep1); sq.write(0, ctrl1)
            elif counter == at2:
                sq.write(1, sweep2); sq.write(0, ctrl2)
            counter -= 1                                       # DecrementSfx1Length
            if counter == 0:
                sq.length = 0                                  # StopSquare1Sfx: $4015
            frames.append(clock_frame([sq])[0])
            f += 1
            if counter == 0:
                break
        while frames and frames[-1] is None:
            frames.pop()
        label = f"Sound{slot}_{name}"
        att0 = jump_attenuation(next(s[1] for s in frames if s))
        lines = header(slot, label, att0, f"; SMB1 {sfx} (square 1): envelope, sweep and length counter"
                                          f" simulated; {len(frames)} frames; volume +{JUMP_VOLUME_BOOST * 2} dB.")
        emit_psg(lines, frames, jump_attenuation, pulse_note, att0)
        write(file, lines)
        print(f"{name}: {frames}")


def music_bytes(start_label, stop_label):
    """All .db bytes from start_label up to stop_label (labels in between are part of it)."""
    lines = open(MUSIC_ASM).read().splitlines()
    i = next(n for n, l in enumerate(lines) if l.strip().startswith(start_label + ":"))
    out = []
    for l in lines[i + 1:]:
        s = l.split(";")[0].strip()
        if s.startswith(stop_label + ":"):
            break
        if s.lower().startswith(".db"):
            out += [int(v.strip().lstrip("$"), 16) for v in s[3:].split(",")]
    return out


TRIANGLE_ATTENUATION = 2     # the triangle has no volume control; about a pulse at volume 10-12 in the NES mix


def death_music():
    """DeathMusic through SMB1's music engine (audio/engine.asm), frame by frame:
    LoadEventMusic (stops both square sfx, resets the triangle), then each frame
    HandleSquare2Music, HandleSquare1Music, HandleTriangleMusic as they run for
    death music (EventMusicBuffer = death, AreaMusicBuffer cleared): square 2
    keeps LoadControlRegs' $82/$7F (no envelope table), square 1 rewrites its
    sweep with AltRegContentFlag ($94 after its $00 byte) every frame, the
    triangle keeps the $1F control written with each length byte, no noise.
    Ends at square 2's $00. Written as an S2 song: square 1/2 and the triangle
    on PSG1-3 (the triangle an octave below a pulse with the same timer)."""
    hdr_line = next(l for l in open(MUSIC_ASM).read().splitlines() if l.strip().startswith(".db")
                    and "DeathMusData" in l)
    hdr = [t.strip() for t in hdr_line.split(";")[0].strip()[3:].split(",")]
    nla, tri_off, sq1_off = int(hdr[0].lstrip("$"), 16), int(hdr[3].lstrip("$"), 16), int(hdr[4].lstrip("$"), 16)
    data = music_bytes("DeathMusData", "CastleMusData")
    LEN = db_block(MUSIC_ASM, "MusicLengthLookupTbl")
    sq1, sq2, tri = Pulse(True), Pulse(False), Triangle()
    sq1.length = sq2.length = tri.length = 0                   # StopSquare1/2Sfx, $4015 = $0B then $0F
    sq2_off, c1, c2, ct, len2, lent, alt = 0, 1, 1, 1, 0, 0, 0
    out = []
    while True:
        # HandleSquare2Music
        c2 = (c2 - 1) & 0xFF
        if c2 == 0:
            b = data[sq2_off]; sq2_off += 1
            if b == 0:                                         # EndOfMusicData: silence, stop
                break
            if b & 0x80:                                       # Squ2LengthHandler
                len2 = LEN[(b & 7) + nla]
                b = data[sq2_off]; sq2_off += 1
            if dump_freq(sq2, b):                              # SetFreq_Squ2, LoadControlRegs
                sq2.write(0, 0x82); sq2.write(1, 0x7F)
            else:                                              # rest: Dump_Sq2_Regs with X=4, Y=note
                sq2.write(0, 0x04); sq2.write(1, b)
            c2 = len2
        # HandleSquare1Music
        if sq1_off:
            c1 = (c1 - 1) & 0xFF
            if c1 == 0:
                b = data[sq1_off]; sq1_off += 1
                while b == 0:                                  # alternate control regs for death music
                    sq1.write(0, 0x83); sq1.write(1, 0x94); alt = 0x94
                    b = data[sq1_off]; sq1_off += 1
                idx = (b & 1) << 2 | (b >> 7 & 1) << 1 | (b >> 6 & 1)   # AlternateLengthHandler: d0,d7,d6
                c1 = LEN[idx + nla]
                note = b & 0x3E
                if dump_freq(sq1, note):                       # SetFreq_Squ1, LoadControlRegs
                    sq1.write(1, 0x7F); sq1.write(0, 0x82)
                else:                                          # Dump_Squ1_Regs with X=0, Y=note
                    sq1.write(1, note); sq1.write(0, 0x00)
            sq1.write(1, alt or 0x7F)                          # DeathMAltReg
        # HandleTriangleMusic
        ct = (ct - 1) & 0xFF
        if ct == 0:
            b = data[tri_off]; tri_off += 1
            if b & 0x80:
                lent = LEN[(b & 7) + nla]
                tri.write(0, 0x1F)
                b = data[tri_off]; tri_off += 1
            if b == 0:
                tri.write(0, 0)
            else:
                dump_freq(tri, b)                              # SetFreq_Tri
                ct = lent
        out.append(clock_frame([sq1, sq2, tri]))

    write_song("MarioDeath", "Mario Death.asm", out,
               [HEADER.replace("smb1-disasm-master", "smb1-disasm-master (SMB1 DeathMusic)"),
                f"; {len(out)} frames at one tick per frame (tempo $FF). The song is stored uncompressed."])
    print(f"death music: {len(out)} frames")


def write_song(label, filename, out, comments, loop=False, tri_fm=None):
    """An uncompressed S2 song from per-frame [square 1, square 2, triangle] samples:
    PSG1-3, a dummy DAC track, one tick per frame (tempo $FF). With loop, every
    track jumps back to its start at the end. With tri_fm (an FM volume), the
    triangle is FM1 with triangle_voice instead of PSG3 (needs loop)."""
    tracks = [("PSG1", [o[0] for o in out], envelope_attenuation, pulse_note, "square 1"),
              ("PSG2", [o[1] for o in out], envelope_attenuation, pulse_note, "square 2")]
    if tri_fm is None:
        tracks.append(("PSG3", [o[2] for o in out], lambda v: TRIANGLE_ATTENUATION, triangle_note, "triangle"))
    lines = comments + [
             f"{label}_Header:",
             "\tsmpsHeaderStartSong 2",
             "\tsmpsHeaderVoiceNull" if tri_fm is None else f"\tsmpsHeaderVoice     {label}_Voices",
             f"\tsmpsHeaderChan      ${1 if tri_fm is None else 2:02X}, ${len(tracks):02X}",
             "\tsmpsHeaderTempo     $01, $FF",
             "",
             f"\tsmpsHeaderDAC       {label}_DAC"]
    if tri_fm is not None:
        if max(TRI_TL) + tri_fm >= 0x80:
            sys.exit("triangle FM volume too low: the total levels would wrap")
        lines.append(f"\tsmpsHeaderFM        {label}_FM1,\t$00, ${tri_fm:02X}")
    att0s = {}
    for ch, frames, att_of, _, _ in tracks:
        att0s[ch] = next((att_of(s[1]) for s in frames if s), 0)
        lines.append(f"\tsmpsHeaderPSG       {label}_{ch},\t$00, ${att0s[ch]:02X}, $00, $00")
    lines += ["", "; DAC Data (none)", f"{label}_DAC:", "\tsmpsStop"]
    if tri_fm is not None:
        lines += ["", "; FM1 Data (triangle)", f"{label}_FM1:", "\tsmpsSetvoice        $00", f"{label}_FM1_Loop:"]
        emit_fm_triangle(lines, [o[2] for o in out], f"{label}_FM1_Loop")
    for ch, frames, att_of, note_of, what in tracks:
        lines += ["", f"; {ch} Data ({what})", f"{label}_{ch}:"]
        emit_psg(lines, frames, att_of, note_of, att0s[ch], f"{label}_{ch}" if loop else None)
    if tri_fm is not None:
        lines += [""] + triangle_voice(f"{label}_Voices")
    path = os.path.join(S2, "sound", "music", filename)
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {path}")


def castle_music():
    """CastleMusic (area music) through SMB1's music engine, frame by frame, as it
    runs with AreaMusicBuffer = CastleMusic and EventMusicBuffer = 0:
    - LoadHeader: note counters 1, square 2 offset 0, AltRegContentFlag 0, $4015 =
      $0B then $0F (the triangle's length counter is cleared), then square 2 runs
      in the same frame.
    - Squares: a note gets LoadControlRegs' $82/$7F and envelope offset 8 (a rest:
      X = $04 / $00, Y = the note byte, offset 0). Every frame MiscSqu*MusicTasks
      writes AreaMusicEnvData[offset] to the control reg (offset read before it is
      decremented, so a note's first frame reads one past the table, the first
      byte of WaterEventMusEnvData) and $7F to the sweep.
    - Triangle: a length byte writes $1F; each note then writes $FF for lengths
      >= $12 and $1F below (castle music rule in TriNoteHandler).
    - No noise (HandleNoiseMusic skips castle music).
    - EndOfMusicData: area music loops (MusicLoopBack -> HandleAreaMusicLoopB ->
      LoadHeader) in the same frame.
    Two passes are simulated and must be identical; one pass is written, looping
    back to its start."""
    # AreaMusicEnvData is 8 bytes; offset 8 reads the next table's first byte
    out, period = looping_music("CastleMusHdr", "CastleMusData", "GameOverMusData",
                                db_block(MUSIC_ASM, "AreaMusicEnvData") + db_block(MUSIC_ASM, "WaterEventMusEnvData")[:1],
                                "castle music")
    write_song("MarioCastle", "Mario Castle.asm", out[:period],
               [HEADER.replace("smb1-disasm-master", "smb1-disasm-master (SMB1 CastleMusic)"),
                f"; One {period}-frame pass at one tick per frame (tempo $FF), looping back to the start",
                "; where SMB1's EndOfMusicData restarts it. The S2 driver skips one tick every 256",
                "; frames (tempo accumulator), so it runs 0.39% slower than SMB1: a one-frame hold",
                "; about every 4.3 seconds. The song is stored uncompressed."],
               loop=True)
    print(f"castle music: {period} frames per pass")


def victory_music():
    """VictoryMusic (event music: SMB1's world 8 ending, Peach rescued) through
    SMB1's music engine, as it runs after PrintVictoryMessages queues it:
    - LoadEventMusic clears AreaMusicBuffer, so LoadControlRegs gives a note
      envelope offset $28 and LoadEnvelopeData reads WaterEventMusEnvData (40
      bytes; offset $28, a note's first frame, reads BowserFlameEnvData's first).
    - Triangle: any event music but death/d4 takes NotDOrD4: $FF for lengths
      >= $12, else $1F (it isn't the win castle music).
    - No noise (AreaMusicBuffer is 0).
    - EndOfMusicData: VictoryMusic is the only event music that loops
      (VictoryMLoopBack -> LoadEventMusic -> LoadHeader), in the same frame.
    Everything else is castle_music's engine run."""
    out, period = looping_music("VictoryMusHdr", "VictoryMusData", "FreqRegLookupTbl",
                                db_block(MUSIC_ASM, "WaterEventMusEnvData") + db_block(MUSIC_ASM, "BowserFlameEnvData")[:1],
                                "victory music", env_start=0x28)
    write_song("MarioVictory", "Mario Victory.asm", out[:period],
               [HEADER.replace("smb1-disasm-master", "smb1-disasm-master (SMB1 VictoryMusic)"),
                f"; One {period}-frame pass at one tick per frame (tempo $FF), looping back to the start",
                "; where SMB1's EndOfMusicData restarts it (VictoryMLoopBack). The S2 driver skips one",
                "; tick every 256 frames, so it runs 0.39% slower than SMB1. Stored uncompressed.",
                "; The squares are PSG1/2 (SMB1 plays them at 50% duty, the PSG's own wave); the",
                f"; triangle is FM1 with a triangle-like voice (harmonics 1/3/5/7), volume ${VICTORY_TRI_FM_VOLUME:02X}."],
               loop=True, tri_fm=VICTORY_TRI_FM_VOLUME)
    print(f"victory music: {period} frames per pass")


# ---------------------------------------------------------------------------
# The triangle on FM (victory music). A PSG square is the wrong instrument for
# the NES triangle (buzzy, and it buried the melody); a triangle wave is odd
# harmonics at 1/n^2, built here from four carriers (algorithm 7) at MUL 1, 3,
# 5, 7 with total levels 20*log10(n^2)/0.75 dB below the fundamental.
# VICTORY_TRI_FM_VOLUME is the channel's attenuation (0.75 dB steps) against
# the PSG squares: the bass/melody balance knob.
# ---------------------------------------------------------------------------
VICTORY_TRI_FM_VOLUME = 0x1C
FM_SAMPLE_RATE = 53693175 / 7 / 144
FM_BASE = [15.39, 16.35, 17.34, 18.36, 19.45, 20.64, 21.84, 23.13, 24.51, 25.98, 27.53, 29.15]  # zMakeFMFrequenciesOctave
FM_FNUM = [int(math.floor(f * 1024 * 1024 * 2 / FM_SAMPLE_RATE + 0.5)) for f in FM_BASE]
TRI_HARMONICS = [1, 3, 5, 7]
TRI_TL = [int(round(40 * math.log10(n) / 0.75)) for n in TRI_HARMONICS]


def fm_note(f):
    """Frequency -> (S2 FM note byte, detune in fnum units, actual): note $81+i plays
    FM_BASE[i % 12] Hz in block i // 12; smpsDetune adds to the fnum."""
    i = min(range(0x5F), key=lambda i: abs(math.log(FM_BASE[i % 12] * 2 ** (i // 12) / f)))   # nearest note
    fnum, block = FM_FNUM[i % 12], i // 12
    d = int(round(f * 2 ** 21 / FM_SAMPLE_RATE / 2 ** block - fnum))
    if not -0x80 <= d < 0x80 or fnum + d >= 0x800:
        sys.exit(f"{f:.1f} Hz: out of the FM range")
    return 0x81 + i, d


def emit_fm_triangle(lines, frames, loop_label):
    """FM notes for per-frame triangle samples (timer, 15) / None (rests)."""
    detune, i = None, 0
    while i < len(frames):
        j = i
        while j < len(frames) and frames[j] == frames[i]:
            j += 1
        dur, s = j - i, frames[i]
        if s is not None:
            f = NES_CPU / (32 * (s[0] + 1))
            note, d = fm_note(f)
            if d != detune:
                lines.append(f"\tsmpsDetune          ${d & 0xFF:02X}\t; {d:+d}")
                detune = d
        first = True
        while dur:
            k = min(dur, 0x7F)
            if s is None:
                lines.append(f"\tdc.b\tnRst, ${k:02X}")
            else:
                if not first:
                    lines.append("\tdc.b\tsmpsNoAttack")      # a held note longer than $7F frames
                lines.append(f"\tdc.b\t${note:02X}, ${k:02X}\t; NES triangle timer ${s[0]:03X}: {f:.1f} Hz")
            first = False
            dur -= k
        i = j
    lines.append(f"\tsmpsJump            {loop_label}")


def triangle_voice(label):
    return [f"{label}:", "; Voice $00: a triangle (odd harmonics at 1/n^2), all four operators carriers",
            "\tsmpsVcAlgorithm     $07",
            "\tsmpsVcFeedback      $00",
            "\tsmpsVcUnusedBits    $00",
            "\tsmpsVcDetune        $00, $00, $00, $00",
            "\tsmpsVcCoarseFreq    " + ", ".join(f"${n:02X}" for n in TRI_HARMONICS),
            "\tsmpsVcRateScale     $00, $00, $00, $00",
            "\tsmpsVcAttackRate    $1F, $1F, $1F, $1F",
            "\tsmpsVcAmpMod        $00, $00, $00, $00",
            "\tsmpsVcDecayRate1    $00, $00, $00, $00",
            "\tsmpsVcDecayRate2    $00, $00, $00, $00",
            "\tsmpsVcDecayLevel    $00, $00, $00, $00",
            "\tsmpsVcReleaseRate   $0F, $0F, $0F, $0F",
            "\tsmpsVcTotalLevel    " + ", ".join(f"${t:02X}" for t in TRI_TL)]


def looping_music(hdr_label, data_label, stop_label, ENV, what, env_start=8):
    """SMB1's engine for a looping song with no noise and the castle/event triangle
    rule (see castle_music), with envelope table ENV; env_start is LoadControlRegs'
    envelope offset for a note ($08 for area music like the castle's, $28 for
    event music). Returns (frames, period)."""
    hdr_line = next(l for l in open(MUSIC_ASM).read().splitlines() if l.strip().startswith(hdr_label + ":"))
    hdr = [int(t.strip().lstrip("$"), 16) for t in hdr_line.split(";")[0].split(".db")[1].split(",")
           if t.strip().startswith("$")]
    nla, tri0, sq10 = hdr[0], hdr[1], hdr[2]
    data = music_bytes(data_label, stop_label)
    LEN = db_block(MUSIC_ASM, "MusicLengthLookupTbl")
    sq1, sq2, tri = Pulse(True), Pulse(False), Triangle()
    st = {}

    def load_header():
        st.update(sq2=0, sq1=sq10, tri=tri0, c1=1, c2=1, ct=1, alt=0)
        tri.length = 0                                         # $4015 = $0B (triangle off), then $0F

    st.update(len2=0, lent=0, env1=0, env2=0)
    load_header()
    out, starts = [], [0]
    while len(starts) < 3:
        # HandleSquare2Music
        st["c2"] = (st["c2"] - 1) & 0xFF
        if st["c2"] == 0:
            b = data[st["sq2"]]; st["sq2"] += 1
            if b == 0:                                         # EndOfMusicData: area music loops
                starts.append(len(out))
                load_header()
                st["c2"] = 0                                   # HandleSquare2Music again: dec 1 -> 0
                b = data[st["sq2"]]; st["sq2"] += 1
            if b & 0x80:                                       # Squ2LengthHandler
                st["len2"] = LEN[(b & 7) + nla]
                b = data[st["sq2"]]; st["sq2"] += 1
            if dump_freq(sq2, b):                              # SetFreq_Squ2, LoadControlRegs
                st["env2"], x, y = env_start, 0x82, 0x7F
            else:                                              # Rest
                st["env2"], x, y = 0, 0x04, b
            sq2.write(0, x); sq2.write(1, y)                   # Dump_Sq2_Regs
            st["c2"] = st["len2"]
        y = st["env2"]                                         # MiscSqu2MusicTasks
        if y:
            st["env2"] -= 1
        sq2.write(0, ENV[y]); sq2.write(1, 0x7F)
        # HandleSquare1Music
        st["c1"] = (st["c1"] - 1) & 0xFF
        if st["c1"] == 0:
            b = data[st["sq1"]]; st["sq1"] += 1
            while b == 0:                                      # (death music only, kept for completeness)
                sq1.write(0, 0x83); sq1.write(1, 0x94); st["alt"] = 0x94
                b = data[st["sq1"]]; st["sq1"] += 1
            st["c1"] = LEN[((b & 1) << 2 | (b >> 7 & 1) << 1 | (b >> 6 & 1)) + nla]   # AlternateLengthHandler
            note = b & 0x3E
            if dump_freq(sq1, note):                           # SetFreq_Squ1, LoadControlRegs
                st["env1"], x, y = env_start, 0x82, 0x7F
            else:
                st["env1"], x, y = 0, 0x00, note
            sq1.write(1, y); sq1.write(0, x)                   # Dump_Squ1_Regs
        y = st["env1"]                                         # MiscSqu1MusicTasks
        if y:
            st["env1"] -= 1
        sq1.write(0, ENV[y])
        sq1.write(1, st["alt"] or 0x7F)                        # DeathMAltReg
        # HandleTriangleMusic
        st["ct"] = (st["ct"] - 1) & 0xFF
        if st["ct"] == 0:
            b = data[st["tri"]]; st["tri"] += 1
            if b & 0x80:
                st["lent"] = LEN[(b & 7) + nla]
                tri.write(0, 0x1F)
                b = data[st["tri"]]; st["tri"] += 1
            if b == 0:                                         # LoadTriCtrlReg with 0
                tri.write(0, 0)
            else:                                              # TriNoteHandler
                dump_freq(tri, b)
                st["ct"] = st["lent"]
                tri.write(0, 0xFF if st["lent"] >= 0x12 else 0x1F)
        out.append(clock_frame([sq1, sq2, tri]))

    period = starts[1] - starts[0]
    if starts[2] - starts[1] != period or out[:period] != out[period:2 * period]:
        sys.exit(f"{what}: the second pass differs from the first")
    return out, period


