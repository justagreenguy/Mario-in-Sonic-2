#!/usr/bin/env python3
"""
nes_sfx2smps.py - convert SMB1's power-up, power-down, fireball, bump and
swim/stomp sounds into Sonic 2 SMPS sound effects on a PSG tone channel.

    python -I tools/nes_sfx2smps.py

Reads (no hardcoded sound data):
    smb1-disasm-master/main.asm         PowerUpGrabFreqData, PlayPowerUpGrab,
                                        PlayPipeDownInj / ContinuePipeDownInj
    smb1-disasm-master/audio/music.asm  FreqRegLookupTbl
    s2disasm-master/s2.sounddriver.asm  zPSGFrequencies (S2's PSG note table)
Writes (with marioMode, s2.asm uses these in place of the two unused sounds
D1/D2 - the sound bank has no room for new ones):
    s2disasm-master/sound/sfx/D2 - Mario Power Up.asm    Sfx_PowerUpGrab
    s2disasm-master/sound/sfx/D1 - Mario Power Down.asm  Sfx_PipeDown (injury)

Pitch: NES square f = CPU / (16 * (t + 1)), CPU = 1789773 Hz (NTSC);
  Genesis PSG f = 3579545 / (32 * N). So N = (t + 1) * 3579545 * 16 /
  (32 * 1789773), i.e. (t + 1) to 5 decimal places: pitches carry over exactly.
  Each N is written as the nearest note of S2's PSG table plus a detune
  (smpsDetune), since the S2 driver writes "table divider + detune" to the PSG.
Volume: NES constant volume v/15 -> nearest PSG attenuation (2 dB steps).
Not representable: duty cycles other than 50% (PSG tone is always 50%).

Power-up (PlayPowerUpGrab / ContinuePowerUpGrab): Squ2_SfxLenCounter = $36;
  every frame, when the counter is even, the square 2 timer is set from
  FreqRegLookupTbl[PowerUpGrabFreqData[counter/2 - 1]]; the counter is
  decremented and the sound stops at 0: 27 tones, 2 frames each, played from
  the END of the table backwards. Control $5D: 25% duty, constant volume 13.

Power-down (PlayPipeDownInj / ContinuePipeDownInj): Squ1_SfxLenCounter = $2F;
  square 1 is (re)written only on frames whose counter has bits 0 and 1 clear
  and bit 3 set (six times), with control $9A (50% duty, volume 10), sweep $91
  and timer FreqRegLookupTbl[$44]. The sound is the NES hardware sweep: enabled,
  divider period 1 (one step per frame from the 120 Hz half-frame clock), shift
  1, not negated: every frame the timer grows by timer >> 1 (pitch falls a
  fifth), and the channel is muted as soon as the next target exceeds $7FF.
  The PSG has no sweep, so it is simulated here frame by frame. Each write
  restarts the sweep; the frames between writes are emitted as calls to shared
  sweep subroutines.
"""
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SMB = os.path.join(ROOT, "smb1-disasm-master")
S2 = os.path.join(ROOT, "s2disasm-master")
SFX_DIR = os.path.join(S2, "sound", "sfx")
MAIN_ASM = os.path.join(SMB, "main.asm")

NES_CPU = 1789773.0          # 21477272 / 12
PSG_CLOCK = 3579545.0        # 53693175 / 15
PSG_SAMPLE_RATE = PSG_CLOCK / 16   # s2.constants.asm PSG_Sample_Rate = Z80_Clock/16
HEADER = "; Generated by tools/nes_sfx2smps.py from smb1-disasm-master - do not edit by hand."


def db_block(path, label):
    lines = open(path).read().splitlines()
    i = next(n for n, l in enumerate(lines) if l.strip().startswith(label + ":"))
    out = []
    for l in lines[i + 1:]:
        s = l.split(";")[0].strip()
        if not s:
            continue
        if not s.lower().startswith(".db"):
            break
        out += [int(v.strip().lstrip("$"), 16) for v in s[3:].split(",")]
    return out


def asm_value(pattern):
    m = re.search(pattern, open(MAIN_ASM).read())
    if not m:
        sys.exit(f"main.asm: {pattern!r} not found")
    return [int(g, 16) for g in m.groups()]


def psg_table():
    """S2's zPSGFrequencies, as the dividers zMakePSGFrequency produces."""
    txt = open(os.path.join(S2, "s2.sounddriver.asm")).read()
    i = txt.index("zPSGFrequencies:")
    freqs = []
    for line in txt[i:].splitlines()[1:]:
        s = line.split(";")[0].strip()
        if not s:
            continue
        if not s.startswith("zMakePSGFrequencies"):
            break
        freqs += [float(v) for v in s.split(None, 1)[1].split(",")]
    # zMakePSGFrequency function frequency,min(3FFh,roundFloatToInteger(PSG_Sample_Rate/(frequency*2)))
    table = [min(0x3FF, int(math.floor(PSG_SAMPLE_RATE / (f * 2) + 0.5))) for f in freqs]
    return table[:-1]        # the last entry is the noise channel's "note"


NOTE_NAMES = ["C", "Cs", "D", "Ds", "E", "F", "Fs", "G", "Gs", "A", "As", "B"]
TABLE = psg_table()
REGTBL = db_block(os.path.join(SMB, "audio", "music.asm"), "FreqRegLookupTbl")


def note_name(idx):
    return f"n{NOTE_NAMES[idx % 12]}{idx // 12}"       # idx 0 = nC0 = $81


def timer_from_offset(a):
    """Dump_Freq_Regs: FreqRegLookupTbl[a] = high 3 bits, [a+1] = low byte (0 = load nothing)."""
    lo, hi = REGTBL[a + 1], REGTBL[a] & 7
    return (hi << 8 | lo) if lo else None


def psg_note(t):
    """NES timer -> (note name, detune, N, description)."""
    n = int(round((t + 1) * PSG_CLOCK * 16 / (32 * NES_CPU)))
    if n > 0x3FF:
        sys.exit(f"timer {t:#x}: below the PSG's lowest pitch")
    idx = min(range(len(TABLE)), key=lambda i: abs(TABLE[i] - n))
    d = n - TABLE[idx]
    if not -128 <= d <= 127:
        sys.exit(f"timer {t:#x}: detune {d} out of range")
    nes_hz = NES_CPU / (16 * (t + 1))
    return note_name(idx), d, n, f"NES timer ${t:03X}: {nes_hz:.1f} Hz"


# User decision (2026-10-09): at their NES-relative volumes (power-up 13/15 ->
# attenuation 1, power-down 10/15 -> 2) the sounds were too quiet next to S2's
# FM sound effects, so they play at the PSG's full volume. Set to False to go
# back to the NES-relative mapping.
PSG_FULL_VOLUME = True


def psg_attenuation(nes_volume):
    if PSG_FULL_VOLUME:
        return 0
    db = -20 * math.log10(nes_volume / 15)
    return int(round(db / 2))


def header(name, label, volume, comment):
    return [HEADER, comment,
            f"{label}_Header:",
            "\tsmpsHeaderStartSong 2",
            "\tsmpsHeaderVoiceNull",
            "\tsmpsHeaderTempoSFX  $01",
            "\tsmpsHeaderChanSFX   $01",
            "",
            f"\tsmpsHeaderSFXChannel cPSG3, {label}_PSG3,\t$00, ${volume:02X}",
            "",
            "; PSG3 Data",
            f"{label}_PSG3:"]


def write(name, lines):
    path = os.path.join(SFX_DIR, name)
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {path}")


