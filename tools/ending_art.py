# Genesis data
def rd(*p):
    return open(os.path.join(S2, *p), "rb").read()


def md_rgb(word):
    return tuple(((word >> s) & 0xE) // 2 * 255 // 7 for s in (0, 4, 8))


def rgb_md(r, g, b):
    lv = lambda v: min(7, max(0, round(v * 7 / 255)))
    return lv(r) << 1 | lv(g) << 5 | lv(b) << 9


def pal_words(data):
    return [int.from_bytes(data[i:i + 2], "big") for i in range(0, len(data), 2)]


