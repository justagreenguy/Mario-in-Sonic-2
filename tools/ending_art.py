# ObjCF sprite mappings
PIECE_RE = re.compile(r"spritePiece\s+(.+)")


def parse_mappings(text):
    frames, cur = [], None
    for line in text.splitlines():
        if re.match(r"\s*Map_objCF_\w+:\s*spriteHeader", line):
            cur = []
            frames.append(cur)
        m = PIECE_RE.search(line)
        if m and cur is not None:
            cur.append([int(v.replace("$", "0x"), 0) for v in m.group(1).split(",")])
    return frames        # [x, y, w, h, tile, xflip, yflip, pal, pri]


def render_piece(img, ox, oy, pc, tiles, base):
    x, y, w, h, tile, xf, yf, pal, _ = pc
    for col in range(w):
        for row in range(h):
            px = tiles[tile - base + col * h + row]
            if xf:
                px = hflip(px)
            if yf:
                px = vflip(px)
            cx = (w - 1 - col) if xf else col
            cy = (h - 1 - row) if yf else row
            blit(img, [[v | pal << 4 if v else 0 for v in r] for r in px], ox + x + cx * 8, oy + y + cy * 8)


def is_char(pc):
    return pc[4] < MINI_TORNADO


def bbox(frame):
    xs = [p[0] for p in frame] + [p[0] + p[2] * 8 for p in frame]
    ys = [p[1] for p in frame] + [p[1] + p[3] * 8 for p in frame]
    return min(xs), min(ys), max(xs), max(ys)


def sprite_canvas(orig_frame):
    """Canvas (origin x, origin y, w, h) of a frame, from S2's own mappings so
    it never changes between exports."""
    x0, y0, x1, y1 = bbox(orig_frame)
    m = SPRITE_MARGIN
    w = (x1 - x0 + 2 * m + 7) // 8 * 8
    h = (y1 - y0 + 2 * m + 7) // 8 * 8
    return m - x0, m - y0, w, h


def pieces_from_image(img, ox, oy, pri, where):
    """Cover the image's non-empty 8x8 cells (grid from the canvas corner) with
    pieces of up to 4x4 tiles, one palette line each. -> [(x, y, w, h, line, [px...])]"""
    th, tw = len(img) // 8, len(img[0]) // 8
    cell = {}
    for ty in range(th):
        for tx in range(tw):
            px = tile_at(img, tx, ty)
            if any(v & 15 for row in px for v in row):
                cell[(tx, ty)] = split_line(px, f"{where} tile ({tx},{ty})")
    used, pieces = set(), []
    for ty in range(th):
        for tx in range(tw):
            if (tx, ty) not in cell or (tx, ty) in used:
                continue
            line = cell[(tx, ty)][0]
            ok = lambda x, y: (x, y) in cell and (x, y) not in used and cell[(x, y)][0] == line
            w = 1
            while w < 4 and ok(tx + w, ty):
                w += 1
            h = 1
            while h < 4 and all(ok(tx + i, ty + h) for i in range(w)):
                h += 1
            for i in range(w):
                for j in range(h):
                    used.add((tx + i, ty + j))
            tiles = [cell[(tx + c, ty + r)][1] for c in range(w) for r in range(h)]   # column-major
            pieces.append((tx * 8 - ox, ty * 8 - oy, w, h, line, pri, tiles))
    return pieces


def fmt(v):
    return f"-${-v:X}" if v < 0 else f"${v:X}"


