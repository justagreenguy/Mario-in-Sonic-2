# Aseprite (.aseprite, indexed) - only what this tool needs
def ase_write(path, w, h, palette, layers):
    """palette: [(r, g, b)], layers: [(name, flags, opacity, pixels or None)],
    bottom first. flags: 1 visible, 2 editable."""
    chunks = []

    def chunk(kind, data):
        chunks.append(struct.pack("<IH", len(data) + 6, kind) + data)

    pal = struct.pack("<III8x", len(palette), 0, len(palette) - 1)
    pal += b"".join(struct.pack("<HBBBB", 0, r, g, b, 255) for r, g, b in palette)
    chunk(0x2019, pal)
    for name, flags, opacity, _ in layers:
        nm = name.encode()
        chunk(0x2004, struct.pack("<HHHHHHB3xH", flags, 0, 0, 0, 0, 0, opacity, len(nm)) + nm)
    for li, (_, _, _, px) in enumerate(layers):
        if px is None:
            continue
        raw = bytes(v for row in px for v in row)
        chunk(0x2005, struct.pack("<HhhBHh5xHH", li, 0, 0, 255, 2, 0, w, h) + zlib.compress(raw, 9))
    body = b"".join(chunks)
    frame = struct.pack("<IHHHxxI", 16 + len(body), 0xF1FA, min(len(chunks), 0xFFFF), 100, len(chunks)) + body
    head = struct.pack("<IHHHHHIHIIB3xHBBhhHH84x", 128 + len(frame), 0xA5E0, 1, w, h, 8, 1, 100, 0, 0,
                       0, len(palette), 1, 1, 0, 0, 16, 16)
    assert len(head) == 128
    open(path, "wb").write(head + frame)


def ase_read(path):
    """-> (w, h, palette [(r,g,b)], layers [(name, visible, pixels)]) for frame 0."""
    d = open(path, "rb").read()
    if struct.unpack_from("<H", d, 4)[0] != 0xA5E0:
        raise SystemExit(f"{path}: not an Aseprite file")
    w, h, depth = struct.unpack_from("<HHH", d, 8)
    if depth != 8:
        raise SystemExit(f"{path}: the sprite must be in Indexed colour mode (Sprite > Color Mode > Indexed)")
    trans = d[28]
    pos = 128
    flen, magic, old_n, _, new_n = struct.unpack_from("<IHHHxxI", d, pos)
    assert magic == 0xF1FA
    n = new_n or old_n
    p = pos + 16
    palette = {}
    layers = []
    cels = {}
    for _ in range(n):
        size, kind = struct.unpack_from("<IH", d, p)
        c = d[p + 6:p + size]
        if kind == 0x2019:
            _, first, last = struct.unpack_from("<III", c, 0)
            q = 20
            for i in range(first, last + 1):
                fl, r, g, b, _a = struct.unpack_from("<HBBBB", c, q)
                q += 6
                if fl & 1:
                    q += 2 + struct.unpack_from("<H", c, q)[0]
                palette[i] = (r, g, b)
        elif kind in (0x0004, 0x0011):
            # old palette chunk (Aseprite writes it instead of 0x2019 when no
            # colour has alpha): packets of (skip, count, RGB...); 0x0011 uses 0-63
            npk = struct.unpack_from("<H", c, 0)[0]
            q, i = 2, 0
            for _ in range(npk):
                i += c[q]
                cnt = c[q + 1] or 256
                q += 2
                for _ in range(cnt):
                    r, g, b = c[q:q + 3]
                    if kind == 0x0011:
                        r, g, b = (v * 255 // 63 for v in (r, g, b))
                    palette.setdefault(i, (r, g, b))
                    i += 1
                    q += 3
        elif kind == 0x2004:
            flags, ltype = struct.unpack_from("<HH", c, 0)
            ln = struct.unpack_from("<H", c, 16)[0]
            layers.append([c[18:18 + ln].decode("utf-8", "replace"), bool(flags & 1), ltype])
        elif kind == 0x2005:
            li, x, y, _op, ctype = struct.unpack_from("<HhhBH", c, 0)
            if ctype in (0, 2):
                cw, ch = struct.unpack_from("<HH", c, 16)
                raw = c[20:] if ctype == 0 else zlib.decompress(c[20:])
                cels[li] = (x, y, cw, ch, raw)
        p += size
    out = []
    for li, (name, vis, ltype) in enumerate(layers):
        px = [[trans] * w for _ in range(h)]
        if li in cels:
            x, y, cw, ch, raw = cels[li]
            for r in range(ch):
                for c in range(cw):
                    v = raw[r * cw + c]
                    if v != trans and 0 <= x + c < w and 0 <= y + r < h:
                        px[y + r][x + c] = v
        out.append((name, vis and ltype == 0, px))
    pal = [palette.get(i, (0, 0, 0)) for i in range(max(palette) + 1 if palette else 0)]
    return w, h, pal, out, trans


def art_layer(path, w, h):
    fw, fh, pal, layers, trans = ase_read(path)
    if (fw, fh) != (w, h):
        raise SystemExit(f"{path}: canvas is {fw}x{fh}, must stay {w}x{h}")
    img = [[0] * w for _ in range(h)]
    for name, vis, px in layers:
        if not vis or name.strip().lower() in ("reference", "original"):
            continue
        for r in range(h):
            for c in range(w):
                v = px[r][c]
                if v != trans:
                    img[r][c] = v
    return img, pal


