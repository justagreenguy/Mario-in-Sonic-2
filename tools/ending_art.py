# Enigma
def enigma_decode(data, base):
    n, mask = data[0], data[1]
    inc = (int.from_bytes(data[2:4], "big") + base) & 0xFFFF
    com = (int.from_bytes(data[4:6], "big") + base) & 0xFFFF
    bits = "".join(format(b, "08b") for b in data[6:])
    p = [0]

    def get(k):
        v = int(bits[p[0]:p[0] + k], 2) if k else 0
        p[0] += k
        return v

    def inline():
        v = base
        if mask & 0x10 and get(1):
            v |= 0x8000
        if mask & 0x08 and get(1):
            v += 0x4000
        if mask & 0x04 and get(1):
            v += 0x2000
        if mask & 0x02 and get(1):
            v |= 0x1000
        if mask & 0x01 and get(1):
            v |= 0x0800
        return (v + get(n)) & 0xFFFF

    out = []
    while True:
        if bits[p[0]] == "0":
            t, c = get(2), get(4)
            for _ in range(c + 1):
                if t == 0:
                    out.append(inc)
                    inc = (inc + 1) & 0xFFFF
                else:
                    out.append(com)
            continue
        t, c = get(3), get(4)
        if t == 7 and c == 15:
            return out
        if t == 7:
            out += [inline() for _ in range(c + 1)]
        else:
            v = inline()
            for _ in range(c + 1):
                out.append(v)
                v = (v + (0, 1, -1)[t - 4]) & 0xFFFF


def enigma_encode(words, base):
    """Words already include base. Uses the common-value run (most frequent
    word) and inline literals with palette and flip bits; priority comes from
    base, so every word must match base's priority bit."""
    for w in words:
        assert (w & 0x8000) == (base & 0x8000) and (w & 0x7FF) >= (base & 0x7FF), hex(w)
        # EniDec adds the inline palette bits to base's: lines below base's can't be stored
        assert (w >> 13) & 3 >= (base >> 13) & 3, f"{w:#x}: palette line below the map base's"
    rel = [(w & 0x7FF) - (base & 0x7FF) for w in words]
    n = max(1, max(rel).bit_length())
    mask = 0x0F                                   # palette + flips
    common = max(set(words), key=words.count)
    bits = []

    def lit(w):
        pal, v, h = ((w >> 13) & 3) - ((base >> 13) & 3), (w >> 12) & 1, (w >> 11) & 1
        return format(pal, "02b") + str(v) + str(h) + format((w & 0x7FF) - (base & 0x7FF), f"0{n}b")

    i = 0
    while i < len(words):
        if words[i] == common:
            k = 1
            while i + k < len(words) and k < 16 and words[i + k] == common:
                k += 1
            bits.append("01" + format(k - 1, "04b"))
        else:
            k = 1
            while i + k < len(words) and k < 15 and words[i + k] != common:
                k += 1
            bits.append("111" + format(k - 1, "04b") + "".join(lit(w) for w in words[i:i + k]))
        i += k
    bits.append("1111111")
    s = "".join(bits)
    s += "0" * (-len(s) % 8)
    data = bytes([n, mask]) + (0).to_bytes(2, "big") + ((common - base) & 0xFFFF).to_bytes(2, "big")
    data += int(s, 2).to_bytes(len(s) // 8, "big")
    assert enigma_decode(data, base) == words, "Enigma round trip failed"
    return data


