#!/usr/bin/env python3
"""
ending_art.py - edit Sonic 2's ending art (Mario build) in Aseprite.

    python -I tools/ending_art.py export [--force]   # S2's original art -> ending_art/*.aseprite
    python -I tools/ending_art.py import             # ending_art/*.aseprite -> game data
    python -I tools/ending_art.py luigi [--force]    # ending_art/luigi/ from Mario's sprites

Run from so-retro. Luigi has his own character frames (ending_art/luigi/
sprite_07..0E): while he plays, palette line 0 entry $2 is his green, so
Mario's frames would show green wherever line 0's dark blue was. `luigi`
makes them from Mario's current frames, recoloured like the in-game Luigi
(LUIGI_RECOLOUR: red -> white, blue -> green), on Luigi's palette; only
missing files unless --force. `export` also creates any that are missing.
The photos and close-up are shared. `export` only writes files that don't exist yet (--force
overwrites them with S2's originals again). `import` regenerates (never hand-edit):
    art/nemesis/mario_ending/*.nem, mappings/misc/mario_ending/*.eni,
    mappings/sprite/MarioEndingCF.asm, art/palettes/mario_ending/Photo1-4.bin,
    mario/mario_ending_art.asm
then decodes what it wrote and checks it against the Aseprite files pixel for
pixel. Rebuild the ROM afterwards. Previews of the result: tools/out/ending_art/.

The files (all indexed colour; palette index 0 is transparent):
  photo1..4.aseprite   the flashback pictures, 96x72. Each has its own
                       16-colour palette (S2 shares Pal_AD1E): edit the colours
                       freely, import writes them too (rounded to the Genesis'
                       8 levels per channel). Colour 0 is transparent.
  closeup.aseprite     the big Tornado close-up, 184x120 (plane A, 23x15 tiles).
  sprite_07..0E        ObjCF's ending frames: $07-$0B Sonic on the small
                       Tornado (it turns towards the camera), $0C-$0E Sonic
                       jumping at the camera.
The close-up and sprites use the 64-colour palette of the 4 S2 palette lines
at that point (index = line*16 + colour). Those palettes are shared with other
sprites (line 0 is Mario's), so their colours are fixed: palette edits there
are ignored. Every 8x8 tile can only use one line: import snaps each tile to
the line that best matches the colours as drawn (the file's palette RGB), and
each pixel to its nearest colour on that line, and lists the tiles it changed
(snap_to_lines). Index 16/32/48 (colour 0 of lines 1-3) count as transparent.

Layers: everything visible except layers named "Reference" or "Original" is
flattened and imported. "Reference" (locked) holds the parts that aren't
yours to change, e.g. the small Tornado under Sonic; "Original" (hidden)
holds S2's Sonic for comparison. Don't resize the canvas: the sprite frames'
origin depends on it.

VRAM budgets (import fails if exceeded): photos 108 tiles each, which always
fits (each photo's art is loaded as it comes up, Mario_EndingPhoto); close-up
170 tiles (identical and flipped 8x8 tiles are shared); sprite frames 317
tiles for all eight (each 8x8 tile with any pixel costs one).
"""
