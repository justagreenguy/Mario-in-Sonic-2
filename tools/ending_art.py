# images <-> tiles
def blank(w, h):
    return [[0] * w for _ in range(h)]


def blit(img, px, x, y):
    for r in range(8):
        for c in range(8):
            v = px[r][c]
            if v & 15 and 0 <= y + r < len(img) and 0 <= x + c < len(img[0]):
                img[y + r][x + c] = v


def tile_at(img, tx, ty, ox=0, oy=0):
    return [[img[oy + ty * 8 + r][ox + tx * 8 + c] for c in range(8)] for r in range(8)]


def colour_dist(a, b):
    """Weighted RGB distance (green counts most, as the eye sees it)."""
    return 2 * (a[0] - b[0]) ** 2 + 4 * (a[1] - b[1]) ** 2 + 3 * (a[2] - b[2]) ** 2


def snap_to_lines(img, file_pal, game_pal, where, lines=(0, 1, 2, 3), ranked=False):
    """The close-up and sprites must use the game's fixed 64-colour palette,
    one line per 8x8 tile. Each pixel's colour is what the artist saw (the
    file's palette entry); per tile, pick the line whose colours (1-15) match
    those best, then move every pixel to its nearest colour on that line.
    Only `lines` are candidates; with `ranked`, a tie in colour goes to the
    earliest line in `lines` (else to the line the tile was drawn on).
    Index 0/16/32/48 stay transparent. -> (new image, report lines)"""
    see = lambda v: file_pal[v] if v < len(file_pal) else game_pal[v]
    out = [row[:] for row in img]
    report = []
    for ty in range(len(img) // 8):
        for tx in range(len(img[0]) // 8):
            cells = [(r, c, img[ty * 8 + r][tx * 8 + c]) for r in range(8) for c in range(8)]
            cells = [(r, c, v) for r, c, v in cells if v & 15]
            if not cells:
                continue
            best = None
            for line in lines:
                cost, remap = 0, {}
                for _, _, v in cells:
                    if v not in remap:
                        remap[v] = min(range(line * 16 + 1, line * 16 + 16),
                                       key=lambda k: colour_dist(see(v), game_pal[k]))
                    cost += colour_dist(see(v), game_pal[remap[v]])
                on_line = sum(1 for _, _, v in cells if v >> 4 == line)
                key = (cost, lines.index(line)) if ranked else (cost, -on_line, line)
                if best is None or key < best[0]:
                    best = (key, line, remap)
            _, line, remap = best
            changed = 0
            for r, c, v in cells:
                if remap[v] != v:
                    out[ty * 8 + r][tx * 8 + c] = remap[v]
                    changed += 1
            if changed:
                inexact = sorted({v for _, _, v in cells if colour_dist(see(v), game_pal[remap[v]])})
                note = f", no exact match for index {', '.join(map(str, inexact))}" if inexact else ""
                report.append(f"  {where} tile ({tx},{ty}) at x={tx * 8} y={ty * 8}: "
                              f"{changed} pixels moved to line {line}{note}")
    return out, report


def split_line(px, where):
    """64-colour pixels -> (line, 16-colour pixels); one line per tile."""
    lines = {v >> 4 for row in px for v in row if v & 15}
    if len(lines) > 1:
        raise SystemExit(f"{where}: one 8x8 tile mixes palette lines {sorted(lines)}")
    return (lines.pop() if lines else 0), [[v & 15 for v in row] for row in px]


def render_map(words, tiles, base, w, h):
    img = blank(w * 8, h * 8)
    for i, word in enumerate(words):
        px = tiles[(word & 0x7FF) - base]
        if word & 0x800:
            px = hflip(px)
        if word & 0x1000:
            px = vflip(px)
        line = (word >> 13) & 3
        blit(img, [[v | (line << 4) if v else 0 for v in row] for row in px], (i % w) * 8, (i // w) * 8)
    return img


def tile_set(tile_list, px):
    """Add px to a deduplicated tile list (with flips). -> (index, hflip, vflip)."""
    key = tuple(map(tuple, px))
    for fl, (hf, vf) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
        k = px
        if hf:
            k = hflip(k)
        if vf:
            k = vflip(k)
        k = tuple(map(tuple, k))
        if k in tile_list[1]:
            return tile_list[1][k], hf, vf
    tile_list[1][key] = len(tile_list[0])
    tile_list[0].append(px)
    return len(tile_list[0]) - 1, 0, 0


def map_from_image(img, w, h, tl, base, where):
    words = []
    for ty in range(h):
        for tx in range(w):
            line, px = split_line(tile_at(img, tx, ty), f"{where} tile ({tx},{ty})")
            i, hf, vf = tile_set(tl, px)
            words.append(base + i | line << 13 | vf << 12 | hf << 11)
    return words


