def tiles_of(data):
    return [data[i:i + 32] for i in range(0, len(data), 32)]


def tile_px(t):
    return [[(t[r * 4 + c // 2] >> (4 if c % 2 == 0 else 0)) & 15 for c in range(8)] for r in range(8)]


def px_tile(px):
    return bytes((px[r][c] << 4) | px[r][c + 1] for r in range(8) for c in range(0, 8, 2))


def hflip(px):
    return [row[::-1] for row in px]


def vflip(px):
    return px[::-1]


def nem_tiles(name):
    return [tile_px(t) for t in tiles_of(nemesis.decompress(rd("art/nemesis", name)))]


