def rgb64(lines):
    return [md_rgb(w) for w in lines]


def export(force):
    os.makedirs(EDIT, exist_ok=True)
    o = originals()
    pal64 = rgb64(o["lines"])
    todo = []
    for i, words in enumerate(o["photo_maps"], 1):
        img = render_map(words, o["photo_tiles"], PHOTO_BASE, 12, 9)
        todo.append((f"photo{i}.aseprite", 96, 72, [md_rgb(w) for w in o["photo_pal"]],
                     [("Art", 3, 255, img)]))
    img = render_map([w & 0x7FFF for w in o["closeup_map"]], o["closeup_tiles"], CLOSEUP_BASE, CLOSEUP_W, CLOSEUP_H)
    todo.append(("closeup.aseprite", CLOSEUP_W * 8, CLOSEUP_H * 8, pal64, [("Art", 3, 255, img)]))
    for f in CHAR_FRAMES:
        fr = o["cf"][f]
        ox, oy, w, h = sprite_canvas(fr)
        art, ref = blank(w, h), blank(w, h)
        for pc in reversed(fr):            # first piece is drawn on top
            if is_char(pc):
                render_piece(art, ox, oy, pc, o["char_tiles"], CHAR_BASE)
            else:
                render_piece(ref, ox, oy, pc, o["mini_tiles"], MINI_TORNADO)
        layers = []
        if any(any(r) for r in ref):
            layers.append(("Reference", 1, 255, ref))
        layers.append(("Original", 0, 128, [row[:] for row in art]))
        layers.append(("Art", 3, 255, art))
        todo.append((f"sprite_{f:02X}.aseprite", w, h, pal64, layers))
    for name, w, h, pal, layers in todo:
        path = os.path.join(EDIT, name)
        if os.path.exists(path) and not force:
            print(f"kept     {name} (exists; --force to overwrite)")
            continue
        ase_write(path, w, h, pal, layers)
        print(f"exported {name} ({w}x{h})")


def export_luigi(force):
    """ending_art/luigi/sprite_07..0E from the current Mario sprite files,
    recoloured (LUIGI_RECOLOUR), on Luigi's palette. Layers: Reference (the
    small Tornado), Original (Mario's art, hidden), Art."""
    o = originals()
    pal64 = rgb64(o["lines"])
    lpal = rgb64(luigi_lines())
    green = md_rgb(luigi_green())
    os.makedirs(luigi_dir(), exist_ok=True)
    for f in CHAR_FRAMES:
        name = f"sprite_{f:02X}.aseprite"
        path = os.path.join(luigi_dir(), name)
        if os.path.exists(path) and not force:
            print(f"kept     luigi/{name} (exists; --force to overwrite)")
            continue
        ox, oy, w, h = sprite_canvas(o["cf"][f])
        mario, fpal = art_layer(os.path.join(EDIT, name), w, h)
        mario, _ = snap_to_lines(mario, fpal, pal64, f"sprite_{f:02X}")
        art = blank(w, h)
        for r in range(h):
            for c in range(w):
                v = mario[r][c]
                if not v & 15:
                    continue
                rgb = LUIGI_RECOLOUR.get(pal64[v], pal64[v]) or green
                if lpal[v] == rgb:
                    art[r][c] = v
                else:                                  # nearest, same line first
                    cands = [k for k in range(64) if k & 15]
                    art[r][c] = min(cands, key=lambda k: (colour_dist(rgb, lpal[k]), k >> 4 != v >> 4))
        ref = blank(w, h)
        for pc in reversed(o["cf"][f]):
            if not is_char(pc):
                render_piece(ref, ox, oy, pc, o["mini_tiles"], MINI_TORNADO)
        layers = []
        if any(any(r) for r in ref):
            layers.append(("Reference", 1, 255, ref))
        layers.append(("Original", 0, 128, mario))
        layers.append(("Art", 3, 255, art))
        ase_write(path, w, h, lpal, layers)
        print(f"exported luigi/{name} ({w}x{h}, recoloured from Mario's)")


