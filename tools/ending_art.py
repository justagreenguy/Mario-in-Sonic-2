def write(rel, data):
    path = os.path.join(S2, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = "w" if isinstance(data, str) else "wb"
    with open(path, mode, newline="\n" if mode == "w" else None) as fh:
        fh.write(data)


def budget(what, used, avail):
    print(f"{what}: {used} of {avail} tiles")
    if used > avail:
        raise SystemExit(f"{what} uses {used} tiles, only {avail} fit in VRAM: simplify the art "
                         f"(blank and repeated/flipped 8x8 tiles are free for the photos and close-up)")


def write_png(path, img, pal, scale=2):
    h, w = len(img), len(img[0])
    rows = []
    for r in range(h):
        row = bytearray()
        for c in range(w):
            v = img[r][c]
            rgb = pal[v] if v & 15 else (64, 64, 64)
            row += bytes(rgb) * scale
        rows += [row] * scale
    raw = b"".join(b"\x00" + bytes(r) for r in rows)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w * scale, h * scale, 8, 2, 0, 0, 0))
    open(path, "wb").write(png + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def import_chars(o, who, folder, gpal, nem):
    """One set of character frames ($07-$0E) -> art/nemesis/mario_ending/<nem>.nem
    and mappings/sprite/<who>EndingCF.asm (MapUnc_<who>EndingCF: ObjCF's
    mappings with those frames replaced). Both sets load to the same VRAM.
    -> (frames, snapped images, snap report)"""
    char_tiles, frames, imgs, snapped = [], {}, {}, []
    tag = "" if who == "Mario" else "luigi/"
    for f in CHAR_FRAMES:
        orig = o["cf"][f]
        ox, oy, w, h = sprite_canvas(orig)
        img, fpal = art_layer(os.path.join(folder, f"sprite_{f:02X}.aseprite"), w, h)
        img, rep = snap_to_lines(img, fpal, gpal, f"{tag}sprite_{f:02X}")
        snapped += rep
        imgs[f] = img
        pri = max((p[8] for p in orig if is_char(p)), default=0)
        new = []
        for x, y, pw, ph, line, pr, tiles in pieces_from_image(img, ox, oy, pri, f"{tag}sprite_{f:02X}"):
            if not -128 <= y <= 127:
                raise SystemExit(f"{tag}sprite_{f:02X}: art too far from the origin vertically")
            new.append([x, y, pw, ph, CHAR_BASE + len(char_tiles), 0, 0, line, pr])
            char_tiles += tiles
        # S2 lists the character first (drawn on top), then the small Tornado
        frames[f] = new + [p for p in orig if not is_char(p)]
    budget(f"{who}'s sprite frames", len(char_tiles), CHAR_END - CHAR_BASE)
    write(f"art/nemesis/mario_ending/{nem}.nem",
          nemesis.compress(b"".join(px_tile(t) for t in char_tiles) or bytes(32)))
    label = f"MapUnc_{who}EndingCF"
    lines = [HEADER, f"; ObjCF's mappings with the ending character frames replaced ({who}).\n",
             f"{label}:\tmappingsTable\n"]
    allf = [frames.get(i, fr) for i, fr in enumerate(o["cf"])]
    for i in range(len(allf)):
        lines.append(f"\tmappingsTableEntry.w\t{label}_{i:02X}\n")
    for i, fr in enumerate(allf):
        lines.append(f"\n{label}_{i:02X}:\tspriteHeader\n")
        for x, y, w, h, t, xf, yf, pal, pr in fr:
            lines.append(f"\tspritePiece\t{fmt(x)}, {fmt(y)}, {w}, {h}, ${t:X}, {xf}, {yf}, {pal}, {pr}\n")
        lines.append(f"{label}_{i:02X}_End\n")
    lines.append("\n\teven\n")
    write(f"mappings/sprite/{who}EndingCF.asm", "".join(lines))
    return frames, imgs, snapped


def do_import():
    o = originals()
    os.makedirs(OUT, exist_ok=True)
    pal64 = rgb64(o["lines"])
    asm = [HEADER, "; Ending art for the Mario build (H26), see tools/ending_art.py.\n\n"]

    # --- photos: each has its own art, map and palette (Mario_EndingPhoto loads
    # them as the photo comes up)
    photos = []
    for i in range(1, 5):
        img, pal = art_layer(os.path.join(EDIT, f"photo{i}.aseprite"), 96, 72)
        if any(v > 15 for row in img for v in row):
            raise SystemExit(f"photo{i}.aseprite: only palette indices 0-15 exist in the photos")
        photos.append(img)
        tl = ([blank(8, 8)], {tuple(map(tuple, blank(8, 8))): 0})
        words = map_from_image(img, 12, 9, tl, PHOTO_BASE, f"photo{i}")
        budget(f"photo {i}", len(tl[0]), PHOTO_END - PHOTO_BASE)
        write(f"art/nemesis/mario_ending/Photo{i}.nem", nemesis.compress(b"".join(px_tile(t) for t in tl[0])))
        write(f"mappings/misc/mario_ending/Photo{i}.eni", enigma_encode(words, PHOTO_BASE))
        pal16 = [rgb_md(*pal[k]) if k < len(pal) else 0 for k in range(16)]
        write(f"art/palettes/mario_ending/Photo{i}.bin", b"".join(w.to_bytes(2, "big") for w in pal16))

    # --- close-up (priority comes from the base, as in S2)
    cw, ch = CLOSEUP_W * 8, CLOSEUP_H * 8
    cimg, fpal = art_layer(os.path.join(EDIT, "closeup.aseprite"), cw, ch)
    cimg, rep = snap_to_lines(cimg, fpal, pal64, "closeup")
    snapped = rep
    tl = ([blank(8, 8)], {tuple(map(tuple, blank(8, 8))): 0})
    cbase = 0x8000 | CLOSEUP_BASE
    cmap = map_from_image(cimg, CLOSEUP_W, CLOSEUP_H, tl, cbase, "closeup")
    budget("close-up", len(tl[0]), CLOSEUP_END - CLOSEUP_BASE)
    write("art/nemesis/mario_ending/Closeup.nem", nemesis.compress(b"".join(px_tile(t) for t in tl[0])))
    write("mappings/misc/mario_ending/Closeup.eni", enigma_encode(cmap, cbase))

    # --- character sprite frames: Mario's set, and Luigi's (ending_art/luigi/,
    # on his palette); the game loads the one being played (Mario_EndingCharArt)
    if not all(os.path.exists(os.path.join(luigi_dir(), f"sprite_{f:02X}.aseprite")) for f in CHAR_FRAMES):
        raise SystemExit("ending_art/luigi/ is missing sprite files: run  python -I tools/ending_art.py luigi")
    sets = []
    for who, folder, gpal, nem in (("Mario", EDIT, pal64, "Character"),
                                   ("Luigi", luigi_dir(), rgb64(luigi_lines()), "LuigiCharacter")):
        frames, imgs, rep = import_chars(o, who, folder, gpal, nem)
        snapped += rep
        sets.append((who, gpal, nem, frames, imgs))

    asm.append("; per photo: art, map, palette (Mario_EndingPhoto)\nMario_EndingPhotoTable:\n")
    for i in range(1, 5):
        asm.append(f"\tdc.l\tArtNem_MarioEndingPhoto{i}, MapEng_MarioEndingPhoto{i}, Pal_MarioEndingPhoto{i}\n")
    for i in range(1, 5):
        asm += [f"\teven\nArtNem_MarioEndingPhoto{i}:\tBINCLUDE\t\"art/nemesis/mario_ending/Photo{i}.nem\"\n",
                f"\teven\nMapEng_MarioEndingPhoto{i}:\tBINCLUDE\t\"mappings/misc/mario_ending/Photo{i}.eni\"\n",
                f"\teven\nPal_MarioEndingPhoto{i}:\tBINCLUDE\t\"art/palettes/mario_ending/Photo{i}.bin\"\n"]
    asm += ["\teven\nArtNem_MarioEndingCloseup:\tBINCLUDE\t\"art/nemesis/mario_ending/Closeup.nem\"\n",
            "\teven\nMapEng_MarioEndingCloseup:\tBINCLUDE\t\"mappings/misc/mario_ending/Closeup.eni\"\n",
            "\teven\nArtNem_MarioEndingChar:\t\tBINCLUDE\t\"art/nemesis/mario_ending/Character.nem\"\n",
            "\teven\nArtNem_LuigiEndingChar:\t\tBINCLUDE\t\"art/nemesis/mario_ending/LuigiCharacter.nem\"\n",
            "\teven\n\tinclude\t\"mappings/sprite/MarioEndingCF.asm\"\n",
            "\teven\n\tinclude\t\"mappings/sprite/LuigiEndingCF.asm\"\n"]
    write("mario/mario_ending_art.asm", "".join(asm))

    # --- check: decode what was written, compare with the Aseprite art
    def back(rel, base, w, h, tiles_rel):
        tiles = [tile_px(t) for t in tiles_of(nemesis.decompress(rd(tiles_rel)))]
        return render_map(enigma_decode(rd(rel), base), tiles, base & 0x7FF, w, h)

    def norm(img):
        return [[v if v & 15 else 0 for v in row] for row in img]

    for i in range(1, 5):
        ppal = [md_rgb(w) for w in pal_words(rd(f"art/palettes/mario_ending/Photo{i}.bin"))]
        got = back(f"mappings/misc/mario_ending/Photo{i}.eni", PHOTO_BASE, 12, 9,
                   f"art/nemesis/mario_ending/Photo{i}.nem")
        assert got == norm(photos[i - 1]), f"photo{i} round trip"
        write_png(os.path.join(OUT, f"photo{i}.png"), got, ppal + [(0, 0, 0)] * 48)
    got = back("mappings/misc/mario_ending/Closeup.eni", cbase, CLOSEUP_W, CLOSEUP_H,
               "art/nemesis/mario_ending/Closeup.nem")
    assert got == norm(cimg), "closeup round trip"
    write_png(os.path.join(OUT, "closeup.png"), got, pal64)
    for who, gpal, nem, frames, imgs in sets:
        ctiles = [tile_px(t) for t in tiles_of(nemesis.decompress(rd(f"art/nemesis/mario_ending/{nem}.nem")))]
        prefix = "" if who == "Mario" else "luigi_"
        for f in CHAR_FRAMES:
            ox, oy, w, h = sprite_canvas(o["cf"][f])
            got, full = blank(w, h), blank(w, h)
            for pc in reversed(frames[f]):
                if is_char(pc):
                    render_piece(got, ox, oy, pc, ctiles, CHAR_BASE)
                    render_piece(full, ox, oy, pc, ctiles, CHAR_BASE)
                else:
                    render_piece(full, ox, oy, pc, o["mini_tiles"], MINI_TORNADO)
            assert got == norm(imgs[f]), f"{who} sprite {f:02X} round trip"
            write_png(os.path.join(OUT, f"{prefix}sprite_{f:02X}.png"), full, gpal, 3)
    inexact = [r for r in snapped if "no exact match" in r]
    if len(snapped) > len(inexact):
        print(f"{len(snapped) - len(inexact)} tiles moved to another palette line with their exact colours")
    if inexact:
        print(f"colours changed to the nearest available in {len(inexact)} tiles (check these):\n"
              + "\n".join(inexact))
    print(f"import OK; decoded data matches the (colour-snapped) art. Previews in {os.path.relpath(OUT, ROOT)}")


