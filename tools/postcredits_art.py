#!/usr/bin/env python3
"""
postcredits_art.py - art for the post-credits scene (mario/mario_postcredits.asm).

    python -I tools/postcredits_art.py

Generates (never edit them by hand):
  art/uncompressed/PostCredits_Mario.bin   the message's text tiles ("MARIO"), then Peach
  art/uncompressed/PostCredits_Luigi.bin   the same with "LUIGI" (same size and layout)
  mappings/sprite/PostCreditsText.asm      frame k = message lines 0..k
  mappings/sprite/Peach.asm                SMB1's princess
  mario/mario_postcredits_art.asm          constants + includes (art kept in one 128KB bank)
  tools/out/postcredits/*.png              previews

The message is drawn with sprites, not written into a plane: the Emerald Hill
palm trunks are foreground tiles running up to the top of the screen, and text
cells would cut through them. Each line is cut into words, each word into
pieces of up to 4 letters; every letter has its own tile (pieces need
consecutive tiles), in SMB1's font (gfx/bg.chr, colour 1 = white).

Peach: EnemyGraphicsTable offset $9C (EnemyGfxTableOffsets[$15], the code
CheckForRetainerObj uses), 16x24, sprite palette 2 (EnemyAttributeData[$15])
of CastlePaletteData, as world 8-4 draws her. MirrorEnemyGfx's princess rule
(ESRtnr) h-flips her bottom-right sprite. Colours: the nearest ones in S2's
palette line 0, never the Luigi slot (entry $2 is green while Luigi plays).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import chr2md  # noqa: E402
from chr2md import S2, SMB, Frame, EMPTY, BLANK_TILE, hflip, load_chr, load_bg_chr, parse_db_block  # noqa: E402

OUT = os.path.join(chr2md.HERE, "out", "postcredits")
HEADER = "; Generated by tools/postcredits_art.py - do not edit by hand.\n"

# The message (user's text, 2026-10-12): SMB1's thanks line, then the Lost
# Levels' (SMB2J) world 8 ending message, one line at a time.
THANKS = "THANK YOU {}!"
MESSAGE = [
    "PEACE IS PAVED",
    "WITH KINGDOM SAVED",
    "HURRAH TO {}",
    "OUR ONLY HERO",
    "THIS ENDS YOUR TRIP",
    "OF A LONG FRIENDSHIP",
]
NAMES = {"Mario": "MARIO", "Luigi": "LUIGI"}

# Screen y of each line's top (the scene's camera puts the capsule's top at
# y 114 and the ground at about y 196; the sky above is free)
THANKS_Y = 16
MESSAGE_Y = 40
LINE_STEP = 12

# VRAM budget: the scene loads its art over EHZ's badnik/spike/spring tiles
# (ArtTile_ArtNem_Buzzer $3D2 .. the end of the horizontal spring, $47C)
VRAM_BUDGET = 0x47C - 0x3D2

FONT = {**{chr(ord("0") + i): i for i in range(10)},
        **{chr(ord("A") + i): 0x0A + i for i in range(26)},
        "-": 0x28, "!": 0x2B, ".": 0xAF}


def font_tile(bg, ch, white, shadow):
    """SMB1's glyph in white with a 1-pixel drop shadow (right, below and the
    diagonal): white letters alone vanish over EHZ's white clouds. The glyphs
    leave their last row and column empty, so the shadow fits in the tile."""
    t = bg[FONT[ch]]
    if set(t) - {0, 1}:
        sys.exit(f"font tile for {ch!r} uses colours {sorted(set(t))}")
    on = lambda x, y: 0 <= x < 8 and 0 <= y < 8 and t[y * 8 + x]
    out = []
    for y in range(8):
        for x in range(8):
            if on(x, y):
                out.append(white)
            elif on(x - 1, y) or on(x, y - 1) or on(x - 1, y - 1):
                out.append(shadow)
            else:
                out.append(0)
    return tuple(out)


def text_frames(lines, bg, white, shadow):
    """Tiles and mapping frames for the message lines (frame k = lines 0..k).
    Returns (tiles, frames, layout) with layout = piece positions/sizes."""
    tiles, pieces, layout = [], [], []
    for li, (y, text) in enumerate(lines):
        x0 = (320 - 8 * len(text)) // 2 - 160            # relative to the screen centre
        col = 0
        for word in text.split(" "):
            for k in range(0, len(word), 4):
                chunk = word[k:k + 4]
                t = len(tiles)
                tiles += [font_tile(bg, ch, white, shadow) for ch in chunk]
                px = x0 + 8 * (col + k)
                pieces.append(dict(x=str(px), y=str(y), w=len(chunk), h=1, tile=t, xf=0, yf=0,
                                   tiles=tiles[t:t + len(chunk)], px=px, py=y, line=li))
                layout.append((li, px, y, len(chunk), t))
            col += len(word) + 1
    frames = []
    for k in range(len(lines)):
        f = Frame(f"Lines0to{k}", f"message lines 0-{k}")
        f.pieces = [p for p in pieces if p["line"] <= k]
        frames.append(f)
    return tiles, frames, layout


def peach_art(sprites, main_lines, md_words):
    castle = parse_db_block(main_lines, "CastlePaletteData")[3:]      # BG 0-3, sprite 0-3
    attrib = parse_db_block(main_lines, "EnemyAttributeData")
    gfx_ofs = parse_db_block(main_lines, "EnemyGfxTableOffsets")
    egt = parse_db_block(main_lines, "EnemyGraphicsTable")
    pal = attrib[0x15] & 3
    nes = castle[4 * (4 + pal) + 1:4 * (4 + pal) + 4]
    remap = chr2md.nearest_remap(nes, md_words, f"Peach (castle sprite palette {pal})")
    if chr2md.LUIGI_SLOT in (remap[1], remap[2], remap[3]):
        sys.exit("Peach's colours would use the Luigi slot")
    ids = egt[gfx_ofs[0x15]:gfx_ofs[0x15] + 6]
    t = [EMPTY if i == BLANK_TILE else chr2md.remap(sprites[i], remap) for i in ids]
    # 2x3: rows (t0 t1) (t2 t3) (t4 t5); MirrorEnemyGfx h-flips the bottom-right sprite
    tiles = [t[0], t[2], t[1], t[3], t[4], t[5]]
    f = Frame("Peach", "EnemyGraphicsTable $9C; bottom-right sprite h-flipped (ESRtnr)")
    f.pieces.append(dict(x="-8", y="-12", w=2, h=2, tile=0, xf=0, yf=0, tiles=tiles[:4], px=-8, py=-12))
    f.pieces.append(dict(x="-8", y="4", w=1, h=1, tile=4, xf=0, yf=0, tiles=[tiles[4]], px=-8, py=4))
    f.pieces.append(dict(x="0", y="4", w=1, h=1, tile=5, xf=1, yf=0, tiles=[hflip(tiles[5])], px=0, py=4))
    img = [[0] * 16 for _ in range(24)]
    for (r, c), tile in zip([(0, 0), (0, 1), (1, 0), (1, 1), (2, 0), (2, 1)], [t[0], t[1], t[2], t[3], t[4], hflip(t[5])]):
        for y in range(8):
            for x in range(8):
                img[r * 8 + y][c * 8 + x] = tile[y * 8 + x]
    return tiles, f, remap, nes, img


def main():
    sprites = load_chr(os.path.join(SMB, "gfx", "sprites.chr"))
    bg = load_bg_chr()
    main_lines = open(os.path.join(SMB, "main.asm")).read().splitlines()
    md = open(os.path.join(S2, "art", "palettes", "SonicAndTails.bin"), "rb").read()[:32]
    md_words = [(md[i * 2] << 8) | md[i * 2 + 1] for i in range(16)]
    white = chr2md.nearest_remap([0x30, 0x0F, 0x0F], md_words, "font white")[1]   # NES white
    shadow = chr2md.nearest_remap([0x0F, 0x30, 0x30], md_words, "font shadow")[1]  # NES black
    if chr2md.LUIGI_SLOT in (white, shadow):
        sys.exit("the font's colours would use the Luigi slot")

    peach_tiles, peach_frame, peach_remap, peach_nes, peach_img = peach_art(sprites, main_lines, md_words)

    sets, layout0 = {}, None
    for who, name in NAMES.items():
        lines = [(THANKS_Y, THANKS.format(name))] + \
                [(MESSAGE_Y + i * LINE_STEP, l.format(name)) for i, l in enumerate(MESSAGE)]
        tiles, frames, layout = text_frames(lines, bg, white, shadow)
        if layout0 is None:
            layout0, frames0, text_n = layout, frames, len(tiles)
        elif layout != layout0:
            sys.exit(f"{who}'s message must have the same layout as Mario's (the mappings are shared)")
        sets[who] = (tiles, lines)
    total = text_n + len(peach_tiles)
    if total > VRAM_BUDGET:
        sys.exit(f"{total} tiles: over the scene's VRAM budget of {VRAM_BUDGET}")

    identity = {i: i for i in range(16)}
    art_dir = os.path.join(S2, "art", "uncompressed")
    for who, (tiles, _) in sets.items():
        chr2md.write_bin(os.path.join(art_dir, f"PostCredits_{who}.bin"), tiles + peach_tiles, identity)
    write_mappings(os.path.join(S2, "mappings", "sprite", "PostCreditsText.asm"), frames0,
                   "Post-credits message (origin: the screen's centre column, y 0). Art: PostCredits_*.bin.")
    write_mappings(os.path.join(S2, "mappings", "sprite", "Peach.asm"), [peach_frame],
                   "SMB1's princess (origin: the centre of her 16x24 box). Art: after the text in PostCredits_*.bin.")

    with open(os.path.join(S2, "mario", "mario_postcredits_art.asm"), "w", newline="\n") as fh:
        fh.write(HEADER)
        fh.write("; Post-credits scene art (mario/mario_postcredits.asm). DMA'd from ROM, so the\n")
        fh.write("; block stays inside one 128KB bank.\n\n")
        fh.write(f"PostCredits_TextTiles\t= ${text_n:02X}\t; text tiles (Peach's follow)\n")
        fh.write(f"PostCredits_ArtTiles\t= ${total:02X}\t; tiles in each PostCredits_*.bin\n")
        fh.write(f"PostCredits_Lines\t= {len(MESSAGE) + 1}\t; message lines (mapping frames)\n\n")
        fh.write("\talign\ttiles_to_bytes(1)\n")
        fh.write("PostCreditsArt_Try:\n")
        fh.write("\tif (PostCreditsArt_Try>>17)<>((PostCreditsArt_Try+2*tiles_to_bytes(PostCredits_ArtTiles)-1)>>17)\n")
        fh.write("\t\talign\t$20000\n\tendif\n")
        fh.write("ArtUnc_PostCredits_Mario:\tBINCLUDE\t\"art/uncompressed/PostCredits_Mario.bin\"\n")
        fh.write("ArtUnc_PostCredits_Luigi:\tBINCLUDE\t\"art/uncompressed/PostCredits_Luigi.bin\"\n")
        fh.write("ArtUnc_PostCredits_End:\n")
        fh.write("\tif (ArtUnc_PostCredits_Mario>>17)<>((ArtUnc_PostCredits_End-1)>>17)\n")
        fh.write("\t\tfatal \"The post-credits art crosses a 128KB boundary; DMA would corrupt it.\"\n\tendif\n")
        fh.write("\tif ArtUnc_PostCredits_End-ArtUnc_PostCredits_Mario<>2*tiles_to_bytes(PostCredits_ArtTiles)\n")
        fh.write("\t\tfatal \"PostCredits_ArtTiles is out of date with the generated art.\"\n\tendif\n")
        fh.write("MapUnc_PostCreditsText:\tinclude\t\"mappings/sprite/PostCreditsText.asm\"\n")
        fh.write("MapUnc_Peach:\tinclude\t\"mappings/sprite/Peach.asm\"\n")
        fh.write("\teven\n")

    # previews: the message on sky blue, Peach x4
    os.makedirs(OUT, exist_ok=True)
    pal = chr2md.load_md_palette()
    luigi_pal = list(pal)
    for who, (tiles, lines) in sets.items():
        H = 112
        img = [[0] * 320 for _ in range(H)]
        for (li, px, y, w, t) in layout0:
            for c in range(w):
                tile = tiles[t + c]
                for yy in range(8):
                    for xx in range(8):
                        img[y + yy][160 + px + c * 8 + xx] = tile[yy * 8 + xx]
        sky = (36 * 4, 36 * 5, 252)
        rows = []
        for line in img:
            out = []
            for v in line:
                out += list(pal[v] if v else sky) * 2
            rows += [out] * 2
        chr2md.write_png(os.path.join(OUT, f"text_{who.lower()}.png"), rows)
    chr2md.render_indexed(os.path.join(OUT, "peach.png"), peach_img, luigi_pal, scale=6)
    print(f"text tiles: {text_n}, Peach tiles: {len(peach_tiles)}, total {total} of {VRAM_BUDGET}")
    print(f"font white -> ${white:X}, shadow -> ${shadow:X}; Peach NES {[hex(c) for c in peach_nes]} -> "
          + ", ".join(f"{i}->${peach_remap[i]:X}" for i in (1, 2, 3)))


def write_mappings(path, frames, comment):
    chr2md.write_mappings(path, frames, comment)
    txt = open(path).read().replace(chr2md.HEADER, HEADER)
    with open(path, "w", newline="\n") as fh:
        fh.write(txt)


if __name__ == "__main__":
    main()
