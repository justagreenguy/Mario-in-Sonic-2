def vram_model():
    """The title screen's VRAM (tile -> 8x8 pixels) as S2 loads it."""
    v = [ea.blank(8, 8) for _ in range(0x800)]
    for name, base in [("Main patterns from title screen.nem", 0), ("Sonic and Tails from title screen.nem", 0x150),
                       ("A few menu blocks.nem", 0x3F2), ("1Player2VS.nem", 0x402), ("Standard font.nem", 0x680)]:
        for i, t in enumerate(nem_tiles(name)):
            v[base + i] = t
    return v


def lines_orig():
    w = pal_words(rd("art/palettes/Title Sonic.bin")) + pal_words(rd("art/palettes/Title screen.bin"))
    w += pal_words(rd("art/palettes/Title Background.bin")) + pal_words(rd("art/palettes/Title Emblem.bin"))
    return w


def parse_mappings(text):
    frames, cur = [], None
    for line in text.splitlines():
        if re.match(r"\s*Map_\w+:\s*spriteHeader", line):
            cur = []
            frames.append(cur)
        m = re.search(r"spritePiece\s+(.+)", line)
        if m and cur is not None:
            cur.append([int(v.replace("$", "0x"), 0) for v in m.group(1).split(",")])
    return frames        # [x, y, w, h, tile, xflip, yflip, pal, pri]


def piece_cells(pc):
    """-> [(dx, dy, tile offset, xflip, yflip)] for each 8x8 tile of a piece."""
    x, y, w, h, tile, xf, yf, pal, pri = pc
    out = []
    for col in range(w):
        for row in range(h):
            cx = (w - 1 - col) if xf else col
            cy = (h - 1 - row) if yf else row
            out.append((x + cx * 8, y + cy * 8, col * h + row))
    return out


def render_pieces(img, ox, oy, pieces, vram, base, only=None):
    for pc in reversed(pieces):               # the first piece is drawn on top
        if only and not only(pc):
            continue
        x, y, w, h, tile, xf, yf, pal, pri = pc
        for dx, dy, k in piece_cells(pc):
            px = vram[(base + tile + k) & 0x7FF]
            if xf:
                px = hflip(px)
            if yf:
                px = vflip(px)
            blit(img, [[v | pal << 4 if v else 0 for v in r] for r in px], ox + dx, oy + dy)


def render_plane(words, vram, w, h, img=None, x0=0):
    img = img or blank(SCREEN_W, SCREEN_H)
    for i, word in enumerate(words):
        cx, cy = i % w + x0, i // w
        if cx * 8 >= len(img[0]):
            continue
        px = vram[word & 0x7FF]
        if word & 0x800:
            px = hflip(px)
        if word & 0x1000:
            px = vflip(px)
        line = (word >> 13) & 3
        blit(img, [[v | line << 4 if v else 0 for v in r] for r in px], cx * 8, cy * 8)
    return img


FONT_CODE = {"@": 0xB, ":": 0xC, ".": 0xD, "*": 0xA}
FONT_CODE.update({str(d): d for d in range(10)})
FONT_CODE.update({chr(65 + i): 0xE + i for i in range(26)})


def read_subtitle():
    """title_art/subtitle.txt -> (text, row, column, line) or None."""
    path = os.path.join(EDIT, "subtitle.txt")
    if not os.path.exists(path):
        return None
    cfg = {}
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0]
        if "=" in line:
            k, v = line.split("=", 1)
            cfg[k.strip().lower()] = v.strip()
    text = cfg.get("text", "").upper()
    if not text:
        return None
    bad = sorted({ch for ch in text if ch != " " and ch not in FONT_CODE})
    if bad:
        raise SystemExit(f"subtitle.txt: the font has no {' '.join(bad)}")
    row, line = int(cfg.get("row", 23)), int(cfg.get("line", 3))
    col = cfg.get("column", "centre").lower()
    col = (40 - len(text)) // 2 if col in ("centre", "center", "auto") else int(col)
    if not (0 <= row < 28 and 0 <= col and col + len(text) <= 40 and 0 <= line < 4):
        raise SystemExit("subtitle.txt: the text doesn't fit on the screen at that row/column")
    return text, row, col, line


def copyright_words():
    """CopyrightText: "@ 1992 SEGA" in the standard font at $680, line 0."""
    code = {"@": 0xB}
    code.update({str(d): d for d in range(10)})
    code.update({chr(65 + i): 0xE + i for i in range(26)})
    return [0 if ch == " " else 0x680 + code[ch] for ch in "@ 1992 SEGA"]


def bbox(pieces):
    xs = [p[0] for p in pieces] + [p[0] + p[2] * 8 for p in pieces]
    ys = [p[1] for p in pieces] + [p[1] + p[3] * 8 for p in pieces]
    return min(xs), min(ys), max(xs), max(ys)


def sprite_canvas(f, frames):
    """Canvas (origin x, origin y, w, h) of a sprite file, from S2's own
    mappings (stable between exports); includes the partner part."""
    x0, y0, x1, y1 = bbox(frames[f])
    if f in PARTNER:
        g = PARTNER[f]
        dx = POS[FRAMES[g]][0] - POS[FRAMES[f]][0]
        dy = POS[FRAMES[g]][1] - POS[FRAMES[f]][1]
        a, b, c, d = bbox(frames[g])
        x0, y0, x1, y1 = min(x0, a + dx), min(y0, b + dy), max(x1, c + dx), max(y1, d + dy)
    m = SPRITE_MARGIN
    return m - x0, m - y0, (x1 - x0 + 2 * m + 7) // 8 * 8, (y1 - y0 + 2 * m + 7) // 8 * 8


def originals():
    o = {"vram": vram_model(), "lines": lines_orig()}
    o["bg"] = enigma_decode(rd("mappings/misc", "Mappings for title screen background.eni"), BG_BASE)
    o["bg2"] = enigma_decode(rd("mappings/misc", "Mappings for title screen background 2.eni"), BG_BASE)
    o["logo"] = enigma_decode(rd("mappings/misc", "Sonic the Hedgehog 2 title screen logo mappings.eni"), LOGO_BASE_S2)
    o["frames"] = parse_mappings(open(os.path.join(S2, "mappings/sprite/obj0E.asm")).read())
    o["menu"] = parse_mappings(open(os.path.join(S2, "mappings/sprite/obj0F.asm")).read())
    return o


def locked_entries(o):
    """Palette entries used by things these files don't replace."""
    used = set(range(0, 64, 16)) | set(range(32, 48))          # colour 0 of each line; line 2 entirely
    v = o["vram"]

    def add(tiles, line):
        for t in tiles:
            used.update(line << 4 | c for row in v[t & 0x7FF] for c in row if c)

    add(copyright_words(), 0)
    for fr in o["menu"]:
        for pc in fr:
            add([pc[4] + k for _, _, k in piece_cells(pc)], pc[7])
    for f in KEPT:
        for pc in o["frames"][f]:
            add([SPRITE_BASE + pc[4] + k for _, _, k in piece_cells(pc)], pc[7])
    return used


def scene(o, frames, vram, logo, skip=None):
    """Final title screen: background, banner, characters, Top/TM sprites."""
    img = render_plane(o["bg"], vram, 40, 28)
    render_plane(logo, vram, 40, 28, img)
    for name in ("sonic", "tails", "sonic_hand", "tails_hand"):
        f = FINAL[name]
        if f != skip:
            render_pieces(img, *POS[name], frames[f], vram, SPRITE_BASE, only=lambda p: p[8])
    render_pieces(img, *POS["logo_top"], frames[LOGO_TOP_TM], vram, SPRITE_BASE)
    return img


