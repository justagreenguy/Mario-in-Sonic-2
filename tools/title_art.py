def read_file(name, w, h):
    """-> (art image of the importable layers, special layers dict, palette)."""
    path = os.path.join(EDIT, name)
    fw, fh, pal, layers, trans = ase_read(path)
    if (fw, fh) != (w, h):
        raise SystemExit(f"{name}: canvas is {fw}x{fh}, must stay {w}x{h}")
    art, special = blank(w, h), {}
    for lname, vis, px in layers:
        key = lname.strip().lower()
        if key in ("top", "tm", "cut") and name == "banner.aseprite":
            img = special.setdefault(key, blank(w, h))
            if not vis and key != "cut":
                continue
        elif not vis or key in REFERENCE_NAMES:
            continue
        else:
            img = art
        for r in range(h):
            for c in range(w):
                if px[r][c] != trans:
                    img[r][c] = px[r][c]
    return art, special, pal


class Banks:
    def __init__(self, banks, what):
        self.banks = [[a, b, []] for a, b in banks]
        self.what = what

    def alloc(self, tiles):
        for bank in self.banks:
            a, b, used = bank
            if a + len(used) + len(tiles) <= b:
                used.extend(tiles)
                return a + len(used) - len(tiles)
        raise SystemExit(f"{self.what}: out of VRAM ({self.total()} tiles placed); simplify the art")

    def total(self):
        return sum(len(b[2]) for b in self.banks)


def do_import():
    o = originals()
    os.makedirs(OUT, exist_ok=True)
    v, fr = o["vram"], o["frames"]
    orig = o["lines"]
    locked = locked_entries(o)

    # --- palette edits from every file
    names = ["banner.aseprite"] + [f"sprite_{f:02X}.aseprite" for f in FRAMES]
    sizes = {"banner.aseprite": (SCREEN_W, SCREEN_H)}
    for f in FRAMES:
        sizes[f"sprite_{f:02X}.aseprite"] = sprite_canvas(f, fr)[2:]
    files = {n: read_file(n, *sizes[n]) for n in names}
    new = list(orig)
    edits, warned = {}, []
    for n in names:
        pal = files[n][2]
        for i in range(min(64, len(pal))):
            w = rgb_md(*pal[i])
            if w == orig[i]:
                continue
            if i in locked:
                warned.append(f"  {n}: index {i} (line {i >> 4} colour {i & 15}) is locked, kept S2's colour")
                continue
            if i in edits and edits[i][1] != w:
                raise SystemExit(f"palette index {i} is changed differently in {edits[i][0]} and {n}")
            edits[i] = (n, w)
            new[i] = w
    pal64 = [md_rgb(w) for w in new]
    report = []

    def seen_pal(n):
        """The colours to snap a file's pixels by: its own palette where it
        differs from S2's, else the new palette (so an entry recoloured in
        one file recolours it in all of them instead of being snapped away)."""
        pal = files[n][2]
        return [base64[i] if i >= len(pal) or rgb_md(*pal[i]) == orig[i] else pal[i] for i in range(64)]
    base64 = list(pal64)                             # palette with the artist's edits, before spares

    # --- spare palette entries: a tile whose colours (as drawn) aren't all on
    # one line gets the missing ones copied into unused, unlocked entries of
    # an editable line, so it can keep the artist's exact colours
    art, special, _ = files["banner.aseprite"]
    images = [(art, seen_pal("banner.aseprite"), BANNER_LINES)]
    images += [(special[k], seen_pal("banner.aseprite"), BANNER_LINES) for k in ("top", "tm") if k in special]
    images += [(files[f"sprite_{f:02X}.aseprite"][0], seen_pal(f"sprite_{f:02X}.aseprite"), SPRITE_LINES)
               for f in FRAMES]
    tiles_cols = []
    used = set(edits)                               # entries some tile needs as they are
    for img, see, allowed in images:
        used.update(v for row in img for v in row if v & 15 and rgb_md(*see[v]) == new[v])   # drawn with directly
        for ty in range(len(img) // 8):
            for tx in range(len(img[0]) // 8):
                cols = {rgb_md(*see[img[ty * 8 + r][tx * 8 + c]]) for r in range(8) for c in range(8)
                        if img[ty * 8 + r][tx * 8 + c] & 15}
                if cols:
                    tiles_cols.append((cols, allowed))

    def line_cols(line):
        return {new[line * 16 + e]: line * 16 + e for e in range(15, 0, -1)}

    def spare(ln):
        return [ln * 16 + e for e in range(1, 16) if ln * 16 + e not in locked and ln * 16 + e not in used]

    # pass 1: tiles that fit a line exactly as it is (the banner: only line 3)
    leftover = []
    for cols, allowed in tiles_cols:
        first = allowed[:1] if allowed is BANNER_LINES else allowed
        fits = [ln for ln in first if cols <= set(line_cols(ln))]
        if fits:
            used.update(line_cols(fits[0])[c] for c in cols)
        else:
            leftover.append((cols, allowed))
    # pass 2: the banner tries line 3's spare entries before falling back to
    # another line; the characters take the line missing the fewest colours
    added = []
    for cols, allowed in sorted(leftover, key=lambda t: len(t[0]), reverse=True):
        options = []
        for ln in allowed:
            missing = [c for c in cols if c not in line_cols(ln)]
            if len(missing) <= len(spare(ln)):
                options.append((len(missing), ln, missing))
        if not options:
            continue                                # snapping will pick the nearest colours
        if allowed is BANNER_LINES:
            _, ln, missing = options[0] if options[0][1] == 3 else min(options)
        else:
            _, ln, missing = min(options)
        for c, e in zip(missing, spare(ln)):
            new[e] = c
            used.add(e)
            added.append(f"  line {e >> 4} colour {e & 15} = ${c:03X}")
        used.update(line_cols(ln)[c] for c in cols)
    pal64 = [md_rgb(w) for w in new]

    # --- banner (plane A)
    fpal = seen_pal("banner.aseprite")
    art, rep = snap_to_lines(art, fpal, pal64, "banner Art", BANNER_LINES, ranked=True)
    report += rep
    reserved = {w & 0x7FF for w in o["bg"] + o["bg2"]} | {0}
    plane = {i: v[i] for i in reserved}                 # vram tile -> pixels
    seen = {}
    for i, px in plane.items():
        seen.setdefault(tuple(map(tuple, px)), i)
    free = [i for i in range(*PLANE_BANKS[0]) if i not in reserved] + list(range(*PLANE_BANKS[1]))
    words = []
    for ty in range(28):
        for tx in range(40):
            line, px = split_line(tile_at(art, tx, ty), f"banner tile ({tx},{ty})")
            hit = None
            for hf, vf in ((0, 0), (1, 0), (0, 1), (1, 1)):
                k = px
                if hf:
                    k = hflip(k)
                if vf:
                    k = vflip(k)
                k = tuple(map(tuple, k))
                if k in seen:
                    hit = (seen[k], hf, vf)
                    break
            if hit is None:
                if not free:
                    raise SystemExit(f"banner: more than {len(plane) - len(reserved) + 1} different 8x8 tiles "
                                     f"don't fit in VRAM; simplify it (repeats and mirror images are free)")
                t = free.pop(0)
                plane[t] = px
                seen[tuple(map(tuple, px))] = t
                hit = (t, 0, 0)
            t, hf, vf = hit
            words.append(LOGO_BASE | t | line << 13 | vf << 12 | hf << 11)
    # subtitle (title_art/subtitle.txt): standard-font tiles ($680, loaded by the
    # title screen) written into the banner map, as S2 adds the copyright line
    sub = read_subtitle()
    if sub:
        text, srow, scol, sline = sub
        covered = 0
        for i, ch in enumerate(text):
            if ch == " ":
                continue
            cell = srow * 40 + scol + i
            if any(c & 15 for r in tile_at(art, scol + i, srow) for c in r):
                covered += 1
            words[cell] = LOGO_BASE | (0x680 + FONT_CODE[ch]) | sline << 13
            px = v[0x680 + FONT_CODE[ch]]
            for r in range(8):
                for c in range(8):
                    art[srow * 8 + r][(scol + i) * 8 + c] = px[r][c] | sline << 4 if px[r][c] else 0
        print(f'subtitle: "{text}" at row {srow}, columns {scol}-{scol + len(text) - 1}, line {sline}')
        if covered:
            print(f"warning: the subtitle replaces {covered} banner tiles that had art in them")
    plane_new = len(plane) - len(reserved)
    print(f"banner: {plane_new} new tiles of {plane_new + len(free)}")
    bank_data = []
    for a, b in PLANE_BANKS:
        top = max([i for i in plane if a <= i < b], default=None)
        if top is not None:
            bank_data.append((a, [plane.get(i, blank(8, 8)) for i in range(a, top + 1)]))
    for k, (a, tiles) in enumerate(bank_data):
        write(f"art/nemesis/mario_title/Plane{k}.nem", nemesis.compress(b"".join(px_tile(t) for t in tiles)))
    write("mappings/misc/mario_title/Logo.eni", enigma_encode(words, LOGO_BASE))

    # --- sprite frames
    sprites = Banks(SPRITE_BANKS, "sprite frames")
    out_frames = [None] * len(fr)
    imgs = {}

    def place(pieces_px, pri_default=None):
        """[(x, y, w, h, line, pri, tiles)] -> mapping pieces with allocated tiles."""
        res = []
        for x, y, w, h, line, pri, tiles in pieces_px:
            if not -128 <= y <= 127:
                raise SystemExit("a sprite piece is too far from its origin vertically")
            res.append([x, y, w, h, sprites.alloc(tiles) - SPRITE_BASE, 0, 0, line, pri])
        return res

    for f, name in FRAMES.items():
        ox, oy, w, h = sprite_canvas(f, fr)
        img = files[f"sprite_{f:02X}.aseprite"][0]
        img, rep = snap_to_lines(img, seen_pal(f"sprite_{f:02X}.aseprite"), pal64, f"sprite_{f:02X}", SPRITE_LINES)
        report += rep
        imgs[f] = img
        out_frames[f] = place(pieces_from_image(img, ox, oy, 1, f"sprite_{f:02X}"))
    out_frames[0x08] = out_frames[0x12]              # S2's leftover frame: same as the final one
    lx, ly = POS["logo_top"]
    banner_img = blank(SCREEN_W, SCREEN_H)
    for key in ("top", "tm"):
        special[key], rep = snap_to_lines(special.get(key, blank(SCREEN_W, SCREEN_H)), fpal, pal64,
                                          f"banner {key}", BANNER_LINES, ranked=True)
        report += rep
    top = place(pieces_from_image(special["top"], lx, ly, 1, "banner Top"))
    tm = place(pieces_from_image(special["tm"], lx, ly, 1, "banner TM"))
    # Cut: the banner's own pixels as low-priority sprites, cell by cell
    for i, word in enumerate(words):
        px = plane.get(word & 0x7FF) or v[word & 0x7FF]     # (subtitle: the font in VRAM)
        if word & 0x800:
            px = hflip(px)
        if word & 0x1000:
            px = vflip(px)
        blit(banner_img, [[c | ((word >> 13) & 3) << 4 if c else 0 for c in r] for r in px], (i % 40) * 8, (i // 40) * 8)
    cutmask = special.get("cut", blank(SCREEN_W, SCREEN_H))
    cut_cells = []
    for ty in range(28):
        row = []
        for tx in range(40):
            marked = any(cutmask[ty * 8 + r][tx * 8 + c] for r in range(8) for c in range(8))
            px = tile_at(banner_img, tx, ty)
            if marked and any(c & 15 for r in px for c in r):
                row.append((tx, split_line(px, "cut")))
            else:
                row.append(None)
        cut_cells.append(row)
    cut = []
    for ty, row in enumerate(cut_cells):
        tx = 0
        while tx < 40:
            if row[tx] is None:
                tx += 1
                continue
            line = row[tx][1][0]
            run = [row[tx][1][1]]
            while tx + len(run) < 40 and len(run) < 4 and row[tx + len(run)] and row[tx + len(run)][1][0] == line:
                run.append(row[tx + len(run)][1][1])
            cut.append((tx * 8 - lx, ty * 8 - ly, len(run), 1, line, 0, run))
            tx += len(run)
    cut = place(cut)
    out_frames[LOGO_TOP] = top + cut
    out_frames[LOGO_TOP_TM] = top + cut + tm
    for f in KEPT:
        res = []
        for pc in fr[f]:
            tiles = [v[(SPRITE_BASE + pc[4] + k) & 0x7FF] for k in range(pc[2] * pc[3])]
            res.append(pc[:4] + [sprites.alloc(tiles) - SPRITE_BASE] + pc[5:])
        out_frames[f] = res
    out_frames[MASKING] = fr[MASKING]                # uses the plane art's tile 0 (art_tile set by Obj0E)
    print(f"sprite frames: {sprites.total()} tiles of {sum(b - a for a, b in SPRITE_BANKS)}")
    for k, (a, b, used) in enumerate(sprites.banks):
        if used:
            write(f"art/nemesis/mario_title/Sprites{k}.nem", nemesis.compress(b"".join(px_tile(t) for t in used)))

    lines = [HEADER, "; Obj0E's mappings: Sonic/Tails frames, the emblem top (Top/TM/Cut) and the stars.\n",
             "MapUnc_MarioTitle0E:\tmappingsTable\n"]
    lines += [f"\tmappingsTableEntry.w\tMapUnc_MarioTitle0E_{i:02X}\n" for i in range(len(out_frames))]
    for i, frame in enumerate(out_frames):
        lines.append(f"\nMapUnc_MarioTitle0E_{i:02X}:\tspriteHeader\n")
        for x, y, w, h, t, xf, yf, pal, pr in frame:
            lines.append(f"\tspritePiece\t{fmt(x)}, {fmt(y)}, {w}, {h}, ${t:X}, {xf}, {yf}, {pal}, {pr}\n")
        lines.append(f"MapUnc_MarioTitle0E_{i:02X}_End\n")
    lines.append("\n\teven\n")
    write("mappings/sprite/MarioTitle0E.asm", "".join(lines))

    # --- palettes (same size as S2's files: the s2.asm BINCLUDEs are swapped)
    for k, fname in ((0, "Title Sonic.bin"), (1, "Title screen.bin"), (3, "Title Emblem.bin")):
        write(f"art/palettes/mario_title/{fname}", b"".join(w.to_bytes(2, "big") for w in new[k * 16:k * 16 + 16]))

    asm = [HEADER, "; Title screen art for the Mario build (H27), see tools/title_art.py.\n\n",
           "; Mario_TitleLoadArt: (Nemesis art, VDP write command) pairs, 0-terminated\nMario_TitleArtTable:\n"]
    for k, (a, _) in enumerate(bank_data):
        asm.append(f"\tdc.l\tArtNem_MarioTitlePlane{k}, vdpComm(tiles_to_bytes(${a:X}),VRAM,WRITE)\n")
    for k, (a, b, used) in enumerate(sprites.banks):
        if used:
            asm.append(f"\tdc.l\tArtNem_MarioTitleSprites{k}, vdpComm(tiles_to_bytes(${a:X}),VRAM,WRITE)\n")
    asm.append("\tdc.l\t0\n")
    for k in range(len(bank_data)):
        asm.append(f"\teven\nArtNem_MarioTitlePlane{k}:\tBINCLUDE\t\"art/nemesis/mario_title/Plane{k}.nem\"\n")
    for k, (a, b, used) in enumerate(sprites.banks):
        if used:
            asm.append(f"\teven\nArtNem_MarioTitleSprites{k}:\tBINCLUDE\t\"art/nemesis/mario_title/Sprites{k}.nem\"\n")
    asm += ["\teven\nMapEng_MarioTitleLogo:\tBINCLUDE\t\"mappings/misc/mario_title/Logo.eni\"\n",
            "\teven\n\tinclude\t\"mappings/sprite/MarioTitle0E.asm\"\n"]
    write("mario/mario_title_art.asm", "".join(asm))

    # --- check: rebuild VRAM from what was written and compare
    nv = [row for row in v]
    for k, (a, _) in enumerate(bank_data):
        for i, t in enumerate(tiles_of(nemesis.decompress(rd(f"art/nemesis/mario_title/Plane{k}.nem")))):
            nv[a + i] = tile_px(t)
    for k, (a, b, used) in enumerate(sprites.banks):
        if used:
            for i, t in enumerate(tiles_of(nemesis.decompress(rd(f"art/nemesis/mario_title/Sprites{k}.nem")))):
                nv[a + i] = tile_px(t)
    logo = enigma_decode(rd("mappings/misc/mario_title/Logo.eni"), LOGO_BASE)
    norm = lambda im: [[c if c & 15 else 0 for c in r] for r in im]
    assert norm(render_plane(logo, nv, 40, 28)) == norm(art), "banner round trip"
    assert norm(render_plane(o["bg"], nv, 40, 28)) == norm(render_plane(o["bg"], v, 40, 28)), "background changed"
    for f in FRAMES:
        ox, oy, w, h = sprite_canvas(f, fr)
        got = blank(w, h)
        render_pieces(got, ox, oy, out_frames[f], nv, SPRITE_BASE)
        assert got == norm(imgs[f]), f"sprite {f:02X} round trip"
    for key, pieces in (("top", top), ("tm", tm)):
        got = blank(SCREEN_W, SCREEN_H)
        render_pieces(got, lx, ly, pieces, nv, SPRITE_BASE)
        assert got == norm(special[key]), f"banner {key} round trip"
    for f in KEPT:
        a, b = blank(64, 64), blank(64, 64)
        render_pieces(a, 32, 32, fr[f], v, SPRITE_BASE)
        render_pieces(b, 32, 32, out_frames[f], nv, SPRITE_BASE)
        assert a == b, f"kept frame {f:02X} changed"

    # --- finished screen, and the hardware sprite limits
    img = scene(o, out_frames, nv, logo)
    full_pieces = []
    for name in ("sonic", "tails", "sonic_hand", "tails_hand"):
        px, py = POS[name]
        full_pieces += [(px + p[0], py + p[1], p[2], p[3]) for p in out_frames[FINAL[name]]]
    full_pieces += [(lx + p[0], ly + p[1], p[2], p[3]) for p in out_frames[LOGO_TOP_TM]]
    # low-priority Cut pieces: the banner shows through them where it is opaque
    for x, y, w, h, t, xf, yf, pal, pr in cut:
        for dx, dy, k in piece_cells([x, y, w, h, t, 0, 0, pal, pr]):
            for r in range(8):
                for c in range(8):
                    sy, sx = ly + dy + r, lx + dx + c
                    if 0 <= sy < SCREEN_H and 0 <= sx < SCREEN_W and banner_img[sy][sx] & 15:
                        img[sy][sx] = banner_img[sy][sx]
    render_pieces(img, lx, ly, top + tm, nv, SPRITE_BASE)
    write_png(os.path.join(OUT, "scene.png"), img, pal64, 2)
    per_line = max(sum(1 for x, y, w, h in full_pieces if y <= sl < y + h * 8) for sl in range(SCREEN_H))
    print(f"finished screen: {len(full_pieces)} hardware sprites (max 80), at most {per_line} on one line (max 20)")
    if len(full_pieces) > 80 or per_line > 20:
        print("warning: over the hardware sprite limit; parts will flicker or vanish")
    if warned:
        print("palette edits ignored (locked entries):\n" + "\n".join(warned))
    if edits:
        print(f"palette entries changed: {', '.join(str(i) for i in sorted(edits))}")
    if added:
        print("spare palette entries filled so tiles keep their drawn colours:\n" + "\n".join(added))
    off3 = []
    for name, img in (("Art", art), ("Top", special["top"]), ("TM", special["tm"])):
        for ty in range(SCREEN_H // 8):
            for tx in range(SCREEN_W // 8):
                lines_used = {c >> 4 for r in range(8) for c in tile_at(img, tx, ty)[r] if c & 15}
                if lines_used - {3}:
                    off3.append(f"  {name} tile ({tx},{ty}) at x={tx * 8} y={ty * 8}: line {lines_used.pop()}")
    if off3:
        print(f"warning: {len(off3)} banner tiles aren't on line 3, so they don't fade in with the emblem "
              f"(line 1: shown from the start, line 0: from frame 128). Line 3 has no room for their colours:\n"
              + "\n".join(off3))
    inexact = [r for r in report if "no exact match" in r]
    if len(report) > len(inexact):
        print(f"{len(report) - len(inexact)} tiles moved to another palette line with their exact colours")
    if inexact:
        print(f"colours changed to the nearest available in {len(inexact)} tiles (check these):\n"
              + "\n".join(inexact))
    print(f"import OK; decoded data matches the art. Preview: {os.path.relpath(os.path.join(OUT, 'scene.png'), ROOT)}")


