def export(force):
    os.makedirs(EDIT, exist_ok=True)
    o = originals()
    pal64 = [md_rgb(w) for w in o["lines"]]
    v, fr = o["vram"], o["frames"]
    todo = []

    bg = render_plane(o["bg"], v, 40, 28)
    logo = render_plane(o["logo"], v, 40, 28)
    chars = blank(SCREEN_W, SCREEN_H)
    for name in ("sonic", "tails", "sonic_hand", "tails_hand"):
        render_pieces(chars, *POS[name], fr[FINAL[name]], v, SPRITE_BASE)
    lx, ly = POS["logo_top"]
    top, tm, cut = blank(SCREEN_W, SCREEN_H), blank(SCREEN_W, SCREEN_H), blank(SCREEN_W, SCREEN_H)
    render_pieces(top, lx, ly, fr[LOGO_TOP], v, SPRITE_BASE, only=lambda p: p[8])
    tm_pieces = [p for p in fr[LOGO_TOP_TM] if p not in fr[LOGO_TOP]]
    render_pieces(tm, lx, ly, tm_pieces, v, SPRITE_BASE)
    for pc in fr[LOGO_TOP]:
        if not pc[8]:
            for dx, dy, _ in piece_cells(pc):
                for r in range(8):
                    for c in range(8):
                        cut[ly + dy + r][lx + dx + c] = 0x31
    copy = blank(SCREEN_W, SCREEN_H)
    for i, t in enumerate(copyright_words()):
        blit(copy, v[t], (28 + i) * 8, 26 * 8)
    todo.append(("banner.aseprite", SCREEN_W, SCREEN_H, [
        ("Background", 1, 255, bg), ("Art", 3, 255, logo), ("Characters", 0, 255, chars),
        ("Top", 3, 255, top), ("TM", 3, 255, tm), ("Cut", 2, 128, cut), ("Copyright", 1, 255, copy)]))

    for f, name in FRAMES.items():
        ox, oy, w, h = sprite_canvas(f, fr)
        art = blank(w, h)
        render_pieces(art, ox, oy, fr[f], v, SPRITE_BASE)
        layers = []
        sc = blank(w, h)
        full = scene(o, fr, v, o["logo"], skip=f)
        px, py = POS[name]
        for r in range(h):
            for c in range(w):
                sy, sx = py - oy + r, px - ox + c
                if 0 <= sy < SCREEN_H and 0 <= sx < SCREEN_W:
                    sc[r][c] = full[sy][sx]
        layers.append(("Scene", 0, 255, sc))
        if f in PARTNER:
            g = PARTNER[f]
            part = blank(w, h)
            gx, gy = POS[FRAMES[g]]
            render_pieces(part, ox + gx - px, oy + gy - py, fr[g], v, SPRITE_BASE)
            layers.append(("Hand" if "hand" in FRAMES[g] else "Body", 1, 255, part))
        layers.append(("Original", 0, 128, [row[:] for row in art]))
        layers.append(("Art", 3, 255, art))
        todo.append((f"sprite_{f:02X}.aseprite", w, h, layers))

    for name, w, h, layers in todo:
        path = os.path.join(EDIT, name)
        if os.path.exists(path) and not force:
            print(f"kept     {name} (exists; --force to overwrite)")
            continue
        ase_write(path, w, h, pal64, layers)
        print(f"exported {name} ({w}x{h})")


