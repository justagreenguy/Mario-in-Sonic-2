#!/usr/bin/env python3
"""
title_art.py - edit Sonic 2's title screen art (Mario build) in Aseprite.
A sibling of ending_art.py (it uses that script's Aseprite, Enigma, Nemesis
and colour-snapping code).

    python -I tools/title_art.py export [--force]   # S2's original art -> title_art/*.aseprite
    python -I tools/title_art.py import             # title_art/*.aseprite -> game data

Run from the project folder. `export` only writes missing files (--force overwrites them
with S2's originals). `import` regenerates (never hand-edit):
    art/nemesis/mario_title/*.nem, mappings/misc/mario_title/Logo.eni,
    mappings/sprite/MarioTitle0E.asm, art/palettes/mario_title/*.bin,
    mario/mario_title_art.asm
then decodes it all again, checks it against the Aseprite art and renders the
finished title screen to tools/out/title_art/scene.png. Rebuild the ROM after.

Files (indexed colour, 64-colour palette = the title screen's 4 lines,
index = line*16 + colour; index 0/16/32/48 are transparent):
  banner.aseprite     the whole screen (320x224). Layers:
      Art         the banner (plane A, in front of the background, behind the
                  characters). Any other visible layer without a special name
                  is merged into it.
      Top         sprite drawn IN FRONT of the characters (S2: the top of the
                  emblem, over Sonic's head).
      TM          sprite shown on overseas consoles only (S2: the TM sign).
      Cut         (hidden; imported anyway) marks where the banner covers the
                  characters: in those 8x8 cells the banner is copied into
                  low-priority sprites (S2's trick that puts the emblem's
                  middle in front of Sonic). Colours don't matter.
      Background, Characters, Copyright  references, not imported.
  sprite_XX.aseprite  Obj0E's frames: Sonic 05-07 (rising), 12 (final), 09
                      (his hand); Tails 00-03 (rising), 04 (final), 13 (his
                      hand). Frame 08 (S2's leftover armless frame) becomes a
                      copy of 12. Layers: Art (imported), Body/Hand (the other
                      part, for lining up), Scene (hidden: the rest of the
                      screen), Original (hidden: S2's art).
Don't resize canvases: the sprites' origins depend on them.

Palettes: lines 0 (Sonic), 1 (Tails, stars) and 3 (banner, menu highlight)
can be edited in any file's palette; line 2 (background) can't. Entries that
the menu, the copyright text or the stars use are locked, as is colour 0 of
every line; import warns and keeps the original for those. Every 8x8 tile
uses one line: import snaps each tile to the best-matching line and each
pixel to its nearest colour there, and lists what it changed.

Gotcha (S2's intro): until the falling star (~8 s), a masking sprite hides
the characters on screen lines 112-175, so they seem to rise from behind the
banner. Art below line 112 appears after that.

VRAM: the banner gets the title art's free tiles plus $40C-$4AB; the sprites
$150-$3F1 plus $4BE-$67F. Import reports the use and the hardware sprite
count of the finished screen (80 per screen, 20 per line).
"""
