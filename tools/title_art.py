OUT = os.path.join(HERE, "out", "title_art")
HEADER = "; Generated by tools/title_art.py from title_art/*.aseprite - do not edit by hand.\n"

SPRITE_BASE = 0x150                       # ArtTile_ArtNem_TitleSprites (Obj0E's art_tile)
PLANE_BANKS = [(0x000, 0x150), (0x40C, 0x4AC)]   # banner art: title art slot, then free VRAM
SPRITE_BANKS = [(0x150, 0x3F2), (0x4BE, 0x680)]  # sprite art: S2's slot, then free VRAM
LOGO_BASE_S2 = 0xE000                     # make_art_tile(ArtTile_ArtNem_Title,3,1), S2's map
LOGO_BASE = 0x8000                        # make_art_tile(ArtTile_ArtNem_Title,0,1): H27 lowers the base
                                          # line so the new map's tiles can use any line
BG_BASE = 0x4000                          # make_art_tile(ArtTile_ArtNem_Title,2,0)
SCREEN_W, SCREEN_H = 320, 224
SPRITE_MARGIN = 24

# Obj0E's final positions on screen (TitleScreen_SetFinalState / LogoTop)
POS = {"sonic": (136, 24), "sonic_hand": (193, 65), "tails": (72, 32), "tails_hand": (141, 81),
       "logo_top": (160, 104)}
FRAMES = {0x00: "tails", 0x01: "tails", 0x02: "tails", 0x03: "tails", 0x04: "tails", 0x13: "tails_hand",
          0x05: "sonic", 0x06: "sonic", 0x07: "sonic", 0x12: "sonic", 0x09: "sonic_hand"}
FINAL = {"sonic": 0x12, "sonic_hand": 0x09, "tails": 0x04, "tails_hand": 0x13}
PARTNER = {0x12: 0x09, 0x09: 0x12, 0x04: 0x13, 0x13: 0x04}     # frame -> the other part of the same character
KEPT = [0x0C, 0x0D, 0x0E, 0x0F, 0x10]     # stars and the lone TM: copied as they are
LOGO_TOP, LOGO_TOP_TM, MASKING = 0x0A, 0x0B, 0x11
# When each palette line shows on the title screen: line 1 from the start,
# line 3 fades in from frame 56 (the emblem), line 0 is set at frame 128 (when
# the characters rise), line 2 stays black until the flash at frame 288. So:
SPRITE_LINES = (0, 1, 3)                  # the characters: never line 2
BANNER_LINES = (3, 1, 0)                  # banner/Top/TM: line 3 if at all possible
REFERENCE_NAMES = {"reference", "original", "background", "characters", "copyright", "scene", "body", "hand"}


