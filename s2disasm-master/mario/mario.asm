; ===========================================================================
; Mario (SMB1) as a playable character - master include
; ---------------------------------------------------------------------------
; Included at the very end of the ROM (after the last sound bank) when
; marioMode = 1. Everything here is far from the main S2 code, so ALL calls
; into S2 routines must use absolute long addressing: jsr (X).l / jmp (X).l.
;
; SMB1 routines are translated from smb1-disasm-master; each translated block
; is commented with its original file and line, e.g.
;   ; SMB1 engine/game-mode/player-movement.asm:184 PlayerPhysicsSub
; See CLAUDE.md in the project root for the full plan.
; ===========================================================================

	even

	include	"mario/mario_frames.asm"	; mapping frame IDs (generated by tools/chr2md.py)
	include	"mario/luigi_palette.asm"	; Luigi's green (generated by tools/luigi_palette.py)

; ===========================================================================
; ----------------------------------------------------------------------------
; Object D0 - Mario
; ----------------------------------------------------------------------------
; Modelled on Obj01 (Sonic). The routine layout MUST match Obj01_Index, since
; S2 code outside this object writes these routine numbers directly
; (HurtCharacter sets 4, KillCharacter sets 6, CheckGameOver sets 8, ...).
;
; Phase 2: movement still uses Sonic's physics routines (Sonic_Move,
; Sonic_Jump, ...). Phase 3 replaces them with the SMB1 translations.
ObjMario:
	; a0=character
	tst.w	(Debug_placement_mode).w	; is debug mode being used?
	beq.s	ObjMario_Normal			; if not, branch
	jmp	(DebugMode).l
; ---------------------------------------------------------------------------
ObjMario_Normal:
	moveq	#0,d0
	move.b	routine(a0),d0
	move.w	ObjMario_Index(pc,d0.w),d1
	jmp	ObjMario_Index(pc,d1.w)
; ===========================================================================
ObjMario_Index:	offsetTable
		offsetTableEntry.w ObjMario_Init	;  0 - object init
		offsetTableEntry.w ObjMario_Control	;  2 - main mode
		offsetTableEntry.w ObjMario_Hurt	;  4 - while being knocked back from damage
		offsetTableEntry.w ObjMario_Dead	;  6 - while dying and falling off screen
		offsetTableEntry.w ObjMario_Gone	;  8 - after dying and waiting for the level to restart
		offsetTableEntry.w ObjMario_Respawning	; $A - while waiting for the camera to scroll to the respawn point
		offsetTableEntry.w ObjMario_Ending	; $C - ending cutscene puppet (H25, mario_polish.asm)
; ===========================================================================
; Obj01_Init equivalent
ObjMario_Init:
	addq.b	#2,routine(a0)	; => ObjMario_Control
	; clear all of Mario's SMB1 state (InitializeMemory)
	lea	(Mario_RAM).w,a1
	moveq	#(Mario_RAM_End-Mario_RAM)-1,d1
-	clr.b	(a1)+
	dbf	d1,-
	; SMB1 power state: every life and act starts with 0 rings, i.e. small.
	; Mario_UpdatePower raises it as rings are collected.
	cmpi.w	#PlayerOpt_Luigi,(Player_option).w	; playing Luigi?
	seq.b	(Mario_IsLuigi).w
	cmpi.w	#Difficulty_Mario,(Difficulty_option).w	; MARIO MODE (hard)?
	seq.b	(Mario_HardMode).w
	move.b	#1,(PlayerSize).w		; SMB1: 1 = small
	move.b	#MarioStatus_Small,(PlayerStatus).w
	tst.w	(Demo_mode_flag).w		; the post-credits scene (Mario_PostCreditsStart)?
	bpl.s	+
	jsr	(Mario_PostCreditsInit).l	; Super Mario, and the scene's director (past the art)
+
	move.b	#1,(PlayerFacingDir).w		; facing right
	move.b	#1,(Player_MovingDir).w
	bsr.w	Mario_InitFallForce		; FallMForceData[0], for walking off a ledge before any jump
	st.b	(Mario_LastLoadedDPLC).w	; force the first DPLC upload
	st.b	(Mario_LastLoadedBank).w
	bsr.w	Mario_SetRadius
	bsr.w	Mario_LoadFireballArt	; fireball/explosion tiles -> Tails' tails (free) VRAM slot
	bsr.w	Mario_LoadLifeIcon	; HUD life counter: Mario's face and name (H13)
	move.l	#MapUnc_Mario,mappings(a0)
	move.b	#2,priority(a0)
	move.b	#$18,width_pixels(a0)
	move.b	#1<<render_flags.level_fg,render_flags(a0)
	; Sonic's movement constants: still used by S2's roll physics
	; (Sonic_RollSpeed) during forced rolls, and by speed shoes/water code
	move.w	#$600,(Sonic_top_speed).w
	move.w	#$C,(Sonic_acceleration).w
	move.w	#$80,(Sonic_deceleration).w
	tst.b	(Last_star_pole_hit).w	; starting at a checkpoint?
	bne.s	ObjMario_Init_Continued	; if so, the starpost restored these already
	; Mario's DPLC uploads go to Sonic's VRAM slot (no Sonic exists in this mode)
	move.w	#make_art_tile(ArtTile_ArtUnc_Sonic,0,0),art_tile(a0)
	move.b	#$C,top_solid_bit(a0)
	move.b	#$D,lrb_solid_bit(a0)
	move.w	x_pos(a0),(Saved_x_pos).w
	move.w	y_pos(a0),(Saved_y_pos).w
	move.w	art_tile(a0),(Saved_art_tile).w
	move.w	top_solid_bit(a0),(Saved_Solid_bits).w

ObjMario_Init_Continued:
	move.b	#0,flips_remaining(a0)
	move.b	#4,flip_speed(a0)
	move.b	#0,(Super_Sonic_flag).w
	move.b	#30,air_left(a0)
	subi.w	#$20,x_pos(a0)
	addi.w	#4,y_pos(a0)
	move.w	#0,(Sonic_Pos_Record_Index).w

	move.w	#$3F,d2
-	jsr	(Sonic_RecordPos).l
	subq.w	#4,a1
	move.l	#0,(a1)
	dbf	d2,-

	addi.w	#$20,x_pos(a0)
	subi.w	#4,y_pos(a0)

; ---------------------------------------------------------------------------
; Normal state for Mario (Obj01_Control equivalent)
; ---------------------------------------------------------------------------
ObjMario_Control:
	tst.w	(Debug_mode_flag).w	; is debug cheat enabled?
	beq.s	+
	btst	#button_B,(Ctrl_1_Press).w	; is button B pressed?
	beq.s	+
	move.w	#1,(Debug_placement_mode).w	; change Mario into a ring/item
	clr.b	(Control_Locked).w
	rts
; ---------------------------------------------------------------------------
+	tst.b	(Control_Locked).w	; are controls locked?
	bne.s	+
	move.w	(Ctrl_1).w,(Ctrl_1_Logical).w	; copy new held buttons, to enable joypad control
+
	bsr.w	Mario_TimerTick		; SMB1's NMI: TimerControl, else the frame timers
	bsr.w	Mario_RunPowerTask	; SMB1's GameEngineSubroutine (grow, fire flower, injury)
	bne.w	ObjMario_Frozen		; growing/fire flower: Mario (only) stands still
	bsr.w	Mario_SyncState		; S2 status -> SMB1 Player_State
	bsr.w	Mario_SwimCheck		; SwimmingFlag: in water, or airborne holding C
	bsr.w	Mario_ReadJoypad	; PlayerCtrlRoutine: split the pad into SMB1 button groups
	btst	#0,obj_control(a0)	; is another object controlling Mario?
	bne.s	+			; if yes, skip movement
	moveq	#0,d0
	move.b	status(a0),d0
	andi.w	#1<<status.player.in_air|1<<status.player.rolling,d0	; %0000 %0110
	add.w	d0,d0
	lea	ObjMario_Modes(pc),a1
	movea.l	(a1,d0.w),a1
	jsr	(a1)			; run Mario's movement control code
	bsr.w	Mario_FixSonicRadius	; undo S2 code that reset "the player" to Sonic's radius
	bsr.w	Mario_SetDirections	; PlayerCtrlRoutine:ChkMoveDir, facing -> S2
+
	bsr.w	Mario_ApplyRadius	; size/crouch -> collision radius, feet kept in place
	tst.b	obj_control(a0)		; port: no throwing while an object controls Mario
	bne.s	.noFireball
	bsr.w	ProcFireball_Bubble	; SMB1: fiery Mario throws fireballs (Phase 6)
.noFireball:
	move.b	(A_B_Buttons).w,(PreviousA_B_Buttons).w	; GameEngine: save A/B for next frame
	cmpi.w	#-$100,(Camera_Min_Y_pos).w	; is vertical wrapping enabled?
	bne.s	+
	andi.w	#$7FF,y_pos(a0)		; perform wrapping of Mario's y position
+
	bsr.w	Mario_Display		; display sprite, handle invulnerability/power-up timers
	jsr	(Sonic_RecordPos).l	; record positions for invincibility stars
	bsr.w	Mario_Water		; handle water entry/exit
	move.b	(Primary_Angle).w,next_tilt(a0)
	move.b	(Secondary_Angle).w,tilt(a0)
	tst.b	(WindTunnel_flag).w	; in a wind tunnel?
	beq.s	+
	tst.b	anim(a0)		; is current animation null/id_Walk?
	bne.s	+
	move.b	prev_anim(a0),anim(a0)	; keep the correct animation while in a wind tunnel
+
	bsr.w	Mario_UpdatePower	; rings -> super/fiery
	bsr.w	Mario_Animate
	tst.b	obj_control(a0)		; is object interactions ignore flag set?
	bmi.s	+
	jsr	(TouchResponse).l	; handle object interactions with Mario
+
	bra.w	LoadMarioDynPLC

; ---------------------------------------------------------------------------
; Growing / fire flower: SMB1 halts everything; here only Mario halts (no
; movement, input or object touches), while S2 keeps running around him.
; (Hard mode: also the start of an injury, until the shrink is over.)
ObjMario_Frozen:
	bsr.w	Mario_ApplyRadius
	bsr.w	Mario_Display
	jsr	(Sonic_RecordPos).l
	bsr.w	Mario_Animate
	bra.w	LoadMarioDynPLC

; ===========================================================================
; Movement modes, indexed by status in_air/rolling (same keys as Obj01_Modes).
; Long pointers, since the Sonic routines are far away.
ObjMario_Modes:
	dc.l	Mario_MdNormal	; 0 - on the ground
	dc.l	Mario_MdAir	; 2 - airborne
	dc.l	Mario_MdRoll	; 4 - rolling (only forced rolls: Mario never starts a roll)
	dc.l	Mario_MdAir	; 6 - airborne and rolling

; ===========================================================================
; ---------------------------------------------------------------------------
; Mario when he gets hurt (Obj01_Hurt equivalent)
; ---------------------------------------------------------------------------
ObjMario_Hurt:
	tst.w	(Debug_mode_flag).w
	beq.s	ObjMario_Hurt_Normal
	btst	#button_B,(Ctrl_1_Press).w
	beq.s	ObjMario_Hurt_Normal
	move.w	#1,(Debug_placement_mode).w
	clr.b	(Control_Locked).w
	rts
; ---------------------------------------------------------------------------
ObjMario_Hurt_Normal:
	bsr.w	Mario_TimerTick		; the injury task (shrink)
	bsr.w	Mario_RunPowerTask
	tst.b	(Mario_PowerTask).w	; SMB1 halts Mario for the whole injury task, as the
	bne.s	ObjMario_HurtFrozen	; world is paused (H17): the knockback starts after it
	tst.b	routine_secondary(a0)
	bmi.s	ObjMario_HurtInstantRecover
	jsr	(ObjectMove).l
	addi.w	#$30,y_vel(a0)
	btst	#status.player.underwater,status(a0)
	beq.s	+
	subi.w	#$20,y_vel(a0)
+
	cmpi.w	#-$100,(Camera_Min_Y_pos).w
	bne.s	+
	andi.w	#$7FF,y_pos(a0)
+
	jsr	(Sonic_HurtStop).l	; landing ends the hurt state (via Sonic_ResetOnFloor -> H4)
	bsr.w	Mario_FixSonicRadius
	bsr.w	Mario_ApplyRadius
	jsr	(Sonic_LevelBound).l
	jsr	(Sonic_RecordPos).l
	bsr.w	Mario_Animate
	bsr.w	LoadMarioDynPLC
	jmp	(DisplaySprite).l
; ---------------------------------------------------------------------------
; Injury task running: Mario stands still (no knockback movement yet) while
; he shrinks. Moving during the world pause made him fall through paused
; solid objects, e.g. off the Tornado in SCZ.
ObjMario_HurtFrozen:
	bsr.w	Mario_ApplyRadius
	jsr	(Sonic_RecordPos).l
	bsr.w	Mario_Animate
	bsr.w	LoadMarioDynPLC
	jmp	(DisplaySprite).l
; ---------------------------------------------------------------------------
; Sonic_HurtInstantRecover equivalent (unused in S2, kept for parity)
ObjMario_HurtInstantRecover:
	subq.b	#2,routine(a0)	; => ObjMario_Control
	move.b	#0,routine_secondary(a0)
	jsr	(Sonic_RecordPos).l
	bsr.w	Mario_Animate
	bsr.w	LoadMarioDynPLC
	jmp	(DisplaySprite).l

; ===========================================================================
; ---------------------------------------------------------------------------
; Mario when he dies (Obj01_Dead equivalent)
; ---------------------------------------------------------------------------
ObjMario_Dead:
	tst.w	(Debug_mode_flag).w
	beq.s	+
	btst	#button_B,(Ctrl_1_Press).w
	beq.s	+
	move.w	#1,(Debug_placement_mode).w
	clr.b	(Control_Locked).w
	rts
+
	jsr	(CheckGameOver).l	; lives, game over / time over, level restart
	tst.b	(Mario_HardMode).w
	bne.s	ObjMario_DeadHard
	jsr	(ObjectMoveAndFall).l
ObjMario_DeadShow:
	jsr	(Sonic_RecordPos).l
	bsr.w	Mario_Animate
	bsr.w	LoadMarioDynPLC
	jmp	(DisplaySprite).l
; ---------------------------------------------------------------------------
; Hard mode (rule 6): SMB1's death. KillPlayer (Mario_DeathSound) set
; TimerControl $FF and Y speed $FC; player-death.asm PlayerDeath holds him
; until TimerControl drops below $F0, then he moves under SMB1 gravity
; (MovePlayerVertically; no input, no horizontal speed). S2 has already
; frozen the other objects (RunObjects while the player is dead).
ObjMario_DeadHard:
	bsr.w	Mario_TimerTick		; NMI: TimerControl counts down
	cmpi.b	#$F0,(TimerControl).w	; check master timer control
	bhs.s	ObjMario_DeadShow	; branch to leave if before that point
	jsr	(ObjectMove).l
	bsr.w	MovePlayerVertically
	bra.s	ObjMario_DeadShow

; ===========================================================================
; ---------------------------------------------------------------------------
; Mario when he's offscreen and waiting for the level to restart (Obj01_Gone)
; ---------------------------------------------------------------------------
ObjMario_Gone:
	tst.w	restart_countdown(a0)
	beq.s	+
	subq.w	#1,restart_countdown(a0)
	bne.s	+
	move.w	#1,(Level_Inactive_flag).w
+
	rts

; ===========================================================================
; ---------------------------------------------------------------------------
; Mario waiting for the camera to scroll back to his respawn point
; (Obj01_Respawning; only reachable in 2P mode, kept for parity)
; ---------------------------------------------------------------------------
ObjMario_Respawning:
	tst.w	(Camera_X_pos_diff).w
	bne.s	+
	tst.w	(Camera_Y_pos_diff).w
	bne.s	+
	move.b	#2,routine(a0)	; => ObjMario_Control
+
	bsr.w	Mario_Animate
	bsr.w	LoadMarioDynPLC
	jmp	(DisplaySprite).l

